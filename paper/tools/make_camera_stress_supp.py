"""make_camera_stress_supp.py -- supplement version of the PickGlass-Stress legacy-13 table.

Reads the generated tables/camera_stress_legacy13.tex (camera_aug/score_stress.py; never edited here)
and writes tables/camera_stress_legacy13_supp.tex with two changes: the GPT-6.1-sol flagship change (+3.8)
is marked nominal (dagger) instead of significant (*) (paired CI [0.10, 8.52] barely excludes 0, Wilcoxon
p = 0.34, one render per image), and the caption says that the stars are uncorrected for multiple comparisons;
and the tabular is scaled to the text width.  Numbers are copied unchanged.

    python3 tools/make_camera_stress_supp.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(os.path.dirname(HERE), "tables")


def main():
    src = open(os.path.join(TAB, "camera_stress_legacy13.tex"), encoding="utf-8").read()
    n_before = src.count("(+3.8$^{*}$)")
    assert n_before == 1, n_before
    t = src.replace("(+3.8$^{*}$)", "(+3.8$^{\\dagger}$)")
    t = t.replace(
        "$^{*}$ = paired 95\\,\\% CI excludes 0.",
        "$^{*}$ = paired 95\\,\\% CI excludes 0 (uncorrected for the 10 conditions and 5 methods); "
        "$^{\\dagger}$ = nominal only (CI $[+0.1, +8.5]$, Wilcoxon $p=0.34$, one render per image).")
    assert t.count("uncorrected") == 1
    t = t.replace("\\label{tab:camera_stress}", "\\label{tab:supp_camera_stress}")
    t = re.sub(r"\\begin\{tabular\}(\{[^}]*\})", r"\\resizebox{\\textwidth}{!}{\\begin{tabular}\1", t, count=1)
    t = t.replace("\\end{tabular}", "\\end{tabular}}", 1)
    hdr = ("% Generated by paper/tools/make_camera_stress_supp.py from tables/camera_stress_legacy13.tex\n"
           "% (camera_aug/score_stress.py). Do not edit by hand. Changes: CHECK.md R4 (GPT flagship marked nominal,\n"
           "% stars uncorrected), label, width.\n")
    out = os.path.join(TAB, "camera_stress_legacy13_supp.tex")
    open(out, "w", encoding="utf-8").write(hdr + t)
    print("wrote", out)


if __name__ == "__main__":
    main()
