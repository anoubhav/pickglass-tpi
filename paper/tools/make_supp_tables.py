"""LaTeX tables for supp.tex, generated from the CSVs (no hand-typed numbers).

    <venv2>/bin/python tools/make_supp_tables.py
Reads  tables/legacy13_crop_sensitivity.csv, tables/degradation_legacy13.csv,
       tables/degradation_legacy13_conf.csv,
       ../methods/results/legacy13_vlmcrops_degrade_extra_summary.csv (motion/noise/shadow,
       methods/degrade_vlmcrops_extra.py)
Writes tables/supp_crop_sensitivity.tex, tables/supp_degradation_legacy.tex
"""
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.dirname(HERE)
ROOT = os.path.dirname(PAPER)
TAB = os.path.join(PAPER, "tables")


def f1(x):
    return "--" if not np.isfinite(x) else f"{x:.1f}"


def crop_sensitivity():
    c = pd.read_csv(os.path.join(TAB, "legacy13_crop_sensitivity.csv"))
    L = [r"% Generated by paper/tools/make_supp_tables.py -- do not edit by hand.",
         r"\begin{table}[t]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{2pt}",
         r"\begin{tabular}{@{}llccc@{}}", r"\toprule",
         r"Method & Crop rule & MAPE [95\% CI] & $\le$5\% & $\le$10\% \\", r"\midrule"]
    last = None
    for r in c.itertuples():
        if last is not None and r.method != last:
            L.append(r"\midrule")
        last = r.method
        rule = str(r.crop_rule).split(":")[0].replace("_", r"\_")
        if "seed" in str(r.crop_rule):
            rule = str(r.crop_rule).replace("P1: whole 2019 hand crop", "P1")
        if "xlsx" in str(r.crop_rule):
            rule = "P1 (2019 xlsx)"
        elif "no-blur re-run" in str(r.crop_rule):
            rule = "P1 (re-run)"
        n = int(r.n_counts)
        sfx = "" if n == 26 else f"/{n}"
        name = {"Ours (PG-Lattice: lattice + fusion)": chr(92) + "ours", "2019 dot map + transition count": "2019 dot map",
                "2019 RGB irregularity (weft only)": "2019 RGB irreg.$^a$", "FFT max near-axis peak": "FFT max peak",
                "CNN, synthetic only": "CNN, synthetic"}.get(r.method, r.method)
        L.append(f"{name} & {rule} & "
                 f"{f1(r.MAPE)} [{r.MAPE_lo:.0f}, {r.MAPE_hi:.0f}] & {int(r.n_w5)}{sfx} & {int(r.n_w10)}{sfx} \\\\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\caption{Crop-rule sensitivity on the 13 legacy windows (axis-matched; "
          r"\texttt{legacy13\_crop\_sensitivity.csv}). $^a$Weft only, out of 13. P1: whole 2019 hand crop taken as 1 inch; "
          r"P2: frame-free window from a dark-frame detector; det./trim: the CNN pipeline's detectors; canonical: "
          r"the one crop rule of the main paper. The 2019 dot-map counter is shown for five k-means seeds.}",
          r"\label{tab:supp_crop}", r"\end{table}"]
    open(os.path.join(TAB, "supp_crop_sensitivity.tex"), "w").write("\n".join(L) + "\n")


FAM = [("clean", "clean", [0.0]), ("defocus", "gblur", [1, 2, 3, 4, 6]), ("motion", "motion", [5, 10, 20, 30]),
       ("downscale", "down", [2, 4, 8]), ("jpeg", "jpeg", [90, 50, 20]), ("noise", "noise", [5, 10, 20, 40]),
       ("glare", "glare", [0.05, 0.1, 0.2, 0.3]), ("shadow", "shadow", [0.25, 0.5]),
       ("corners", "corners", [0.02, 0.05, 0.1])]
LAB = {"clean": "Clean", "defocus": r"Defocus $\sigma$ (u)", "motion": "Motion (u)", "downscale": r"Downscale $\times$",
       "jpeg": "JPEG $q$", "noise": r"Noise $\sigma$", "glare": r"Glare (\% area)", "shadow": r"Shadow (\% area)",
       "corners": r"Corners (\% side)"}


def degradation():
    d = pd.read_csv(os.path.join(TAB, "degradation_legacy13.csv"))
    d = d[(d["assign"] == "axis") & (d["run"] == "main")]
    x = pd.read_csv(os.path.join(ROOT, "methods", "results", "legacy13_vlmcrops_degrade_extra_summary.csv"))
    conf = pd.read_csv(os.path.join(TAB, "degradation_legacy13_conf.csv"))
    conf = conf[conf.part == "A_conf_by_condition"]
    meths = [("ours", "ours"), ("log-Gabor", "gabor"), ("CNN", None), ("gpt-6.1-sol P1", None),
             ("gpt-6.1-sol P3", None), ("gemini-3.8-flash P3", None)]
    L = [r"% Generated by paper/tools/make_supp_tables.py -- do not edit by hand.",
         r"\begin{table*}[t]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
         r"\begin{tabular}{@{}llccccccc@{}}", r"\toprule",
         r"Degradation & Level & \ours & log-Gabor & CNN & GPT-6.1-sol P1 & GPT-6.1-sol P3 & Gemini 3.8 Flash P3 & "
         r"Conf.\ (\ours) \\", r"\midrule"]
    for fam, kind, levels in FAM:
        for i, lv in enumerate(levels):
            cells = []
            for name, xkey in meths:
                g = d[(d.method == name) & (d.family == fam) & np.isclose(d.level, lv)]
                if len(g):
                    r = g.iloc[0]
                    ab = "" if r.n_ok == 13 else f"$^{{{13 - int(r.n_ok)}}}$"
                    cells.append(f"{f1(r.MAPE)} / {int(r.n_w10)}{ab}")
                elif xkey is not None:
                    h = x[(x.estimator == xkey) & (x.kind == kind) & np.isclose(x.level, lv)]
                    cells.append(f"{f1(h.iloc[0].MAPE)} / {int(h.iloc[0].n_w10)}" if len(h) else "--")
                else:
                    cells.append("--")
            cf = conf[(conf.kind == kind) & np.isclose(conf.level, lv)] if fam != "clean" else conf[conf.family == "clean"]
            if len(cf):
                cc = f"{cf.iloc[0].conf_mean:.2f}"
            else:
                h = x[(x.estimator == "ours") & (x.kind == kind) & np.isclose(x.level, lv)]
                cc = f"{h.iloc[0].conf_mean:.2f}" if len(h) else "--"
            lvs = "" if fam == "clean" else (f"{100 * lv:g}" if fam in ("glare", "shadow", "corners") else f"{lv:g}")
            L.append(f"{LAB[fam] if i == 0 else ''} & {lvs} & " + " & ".join(cells) + f" & {cc} \\\\")
        if fam != "corners":
            L.append(r"\addlinespace[1pt]")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\caption{Capture degradations on the 13 legacy windows (canonical crops, axis-matched): MAPE (\%) / counts "
          r"within 10\% of the hand count (of 26). Superscripts: images without a count (abstention or no answer). "
          r"Last column: mean confidence of \ours. VLMs were run only at the levels marked; motion, noise and "
          r"shadow were run for the spectral counters only (\texttt{methods/degrade\_vlmcrops\_extra.py}). Sources: "
          r"\texttt{tables/degradation\_legacy13.csv}, \texttt{tables/degradation\_legacy13\_conf.csv}, "
          r"\texttt{methods/results/legacy13\_vlmcrops\_degrade\_extra\_summary.csv}.}",
          r"\label{tab:supp_deg}", r"\end{table*}"]
    open(os.path.join(TAB, "supp_degradation_legacy.tex"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    crop_sensitivity()
    degradation()
    print("wrote tables/supp_crop_sensitivity.tex, tables/supp_degradation_legacy.tex")
