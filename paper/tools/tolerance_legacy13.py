"""Tolerance-referenced metrics on legacy-13 (POST HOC: defined after the legacy scores were known).

Part of the problem definition grounded in textile standards; it lives in the paper tools so that every
number in the paper traces to a CSV under paper/tables. No new predictions: it only re-scores
tables/legacy13_unified_per_count.csv (written by tools/legacy_unified.py), axis-matched.

Writes
  tables/tolerance_legacy13.csv        per method: W_tau (share of counts within tau = 2.5/5/10/15 %) with
                                       image-bootstrap CIs (10k), P_5 / P_10 (share of IMAGES with both counts
                                       within tau), median signed error (bias, %), under/over shares, MAPE
  tables/tolerance_paired.csv          ours vs GPT-6.1-sol P1 (run 0), count level: exact McNemar + bootstrap CI
  tables/tolerance_image_paired.csv    ours vs others, image level (both counts within tau): exact McNemar

  tables/supp_tolerance.tex            supplement table (tab:supp_tolerance) built from tolerance_legacy13.csv

    <venv2>/bin/python tools/tolerance_legacy13.py             (full run, ~11 CPU-min, ~30 min wall under load: pandas bootstrap loop)
    <venv2>/bin/python tools/tolerance_legacy13.py --tex-only  (rewrite the .tex from the CSV only)
"""
