import sys

import numpy as np
import pandas as pd
from scipy.stats import binomtest

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(os.path.dirname(HERE), "tables")
d = pd.read_csv(os.path.join(TAB, "legacy13_unified_per_count.csv"))
d = d[d["assign"] == "axis"].copy()
KEYS = [("ref:loo_mean", "Leave-one-out mean"), ("2019:doc3", "2019 dot map"),
        ("est:ours", "PG-Lattice (ours)"), ("est:gabor", "Log-Gabor bank"), ("est:fft", "FFT max peak"),
        ("cnn:synth_r18", "CNN synthetic-only"), ("countgd:CG-W-ex3-lat", "CountGD cells+lattice (post hoc)"),
        ("vlm:molmo2_8b_bf16|P4q|r0", "Molmo2-8B P4q"),
        ("ft:molmo2_4b_synthft|P1", "Molmo2-4B synthetic LoRA P1"),
        ("vlm:gpt-6.1-sol|P1|r0", "GPT-6.1-sol P1"), ("vlm:gpt-6.1-sol|P1|r1", "GPT-6.1-sol P1 (repeat 1)"),
        ("vlm:gpt-6.1-sol|P1|r2", "GPT-6.1-sol P1 (repeat 2)"),
        ("vlm:gpt-6.1-sol|P3s|r0", "GPT-6.1-sol P3s"), ("vlm:gemini-3.8-flash|P1|r0", "Gemini 3.8 Flash P1"),
        ("vlm:claude-fable-5.1|P1|r0", "Claude Fable 5.1 P1")]
def write_tex():
    r = pd.read_csv(os.path.join(TAB, "tolerance_legacy13.csv")).set_index("key")
    order = [("est:ours", r"\ours"), ("est:gabor", "Log-Gabor bank"), ("est:fft", "FFT max peak"),
             ("cnn:synth_r18", "CNN, synthetic only"), ("countgd:CG-W-ex3-lat", r"CountGD cells$\to$lattice$^b$"),
             ("vlm:molmo2_8b_bf16|P4q|r0", "Molmo2-8B, P4q"), ("ft:molmo2_4b_synthft|P1", "Molmo2-4B + LoRA, P1"),
             ("vlm:gpt-6.1-sol|P1|r0", "GPT-6.1-sol, P1$^c$"), ("vlm:gpt-6.1-sol|P3s|r0", "GPT-6.1-sol, P3s"),
             ("vlm:gemini-3.8-flash|P1|r0", "Gemini 3.8 Flash, P1"), ("vlm:claude-fable-5.1|P1|r0", "Claude Fable 5.1, P1"),
             ("ref:loo_mean", "Leave-one-out mean")]
    reps = [k for k in ("vlm:gpt-6.1-sol|P1|r1", "vlm:gpt-6.1-sol|P1|r2") if k in r.index]
    L = [r"% Generated by paper/tools/tolerance_legacy13.py from tables/tolerance_legacy13.csv -- do not edit by hand.",
         r"\begin{table}[t]", r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{2.4pt}",
         r"\begin{tabular}{@{}lccccr@{}}", r"\toprule",
         r"Method & $W_{2.5}$ & $W_5$ [95\% CI] & $W_{10}$ & $P_5$ (img.) & Bias \\", r"\midrule"]
    for k, name in order:
        if k not in r.index:
            continue
        x = r.loc[k]
        p5 = f"{int(x['n_img_both@5'])}/13"
        if k == "vlm:gpt-6.1-sol|P1|r0" and reps:
            p5 += " (" + "/".join(str(int(r.loc[q, "n_img_both@5"])) for q in reps) + ")"
        L.append(f"{name} & {x['TA@2.5']:.0f} & {x['TA@5']:.0f} [{x['TA@5_lo']:.0f}, {x['TA@5_hi']:.0f}] & "
                 f"{x['TA@10']:.0f} & {p5} & ${x['median_signed_%']:+.1f}$ \\\\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\caption{Tolerance-referenced scores on the 13 legacy windows\LEG (axis-matched; \emph{post hoc}: these "
          r"metrics were defined after the legacy scores were known; on \dataset they are fixed in the scorer before "
          r"labelling). $W_\tau$: \% of the 26 counts within $\tau$\% (image-bootstrap CI, 10k); $P_5$: images with "
          r"both counts within 5\%; Bias: median signed error in \%. $^b$Post hoc. $^c$In brackets: $P_5$ of "
          r"GPT-6.1-sol P1 in two identical repeats.}",
          r"\label{tab:supp_tolerance}", r"\end{table}"]
    open(os.path.join(TAB, "supp_tolerance.tex"), "w").write("\n".join(L) + "\n")
    print("wrote tables/supp_tolerance.tex")


if "--tex-only" in sys.argv:
    write_tex()
    sys.exit(0)


TAUS = [2.5, 5, 10, 15]
rng = np.random.default_rng(0)
B = 10000


def metrics(g):
    e = 100 * (g.pred - g.true) / g.true
    out = {f"TA@{t}": 100 * np.mean(np.abs(e) <= t) for t in TAUS}
    q = np.abs(g.pred - g.true) <= np.maximum(0.05 * g.true, 1.0)
    out["TAq@5"] = 100 * q.mean()
    img = g.assign(ok5=np.abs(e) <= 5, ok10=np.abs(e) <= 10).groupby("image")[["ok5", "ok10"]].all()
    out["img_both@5"] = 100 * img.ok5.mean()
    out["img_both@10"] = 100 * img.ok10.mean()
    out["n_img_both@5"] = int(img.ok5.sum())
    out["n_img_both@10"] = int(img.ok10.sum())
    out["median_signed_%"] = float(np.median(e))
    out["MAPE"] = float(np.mean(np.abs(e)))
    out["under>5%"] = 100 * np.mean(e < -5)
    out["over>5%"] = 100 * np.mean(e > 5)
    return out


def boot_ci(g, stat):
    imgs = g.image.unique()
    groups = {i: g[g.image == i] for i in imgs}
    vals = []
    for _ in range(B):
        s = rng.choice(imgs, len(imgs), replace=True)
        vals.append(stat(pd.concat([groups[i] for i in s])))
    return np.percentile(vals, [2.5, 97.5])


rows = []
for k, name in KEYS:
    g = d[d.key == k].dropna(subset=["pred"]).copy()
    if not len(g):
        continue
    m = metrics(g)
    m.update(method=name, key=k, n_counts=len(g), n_images=g.image.nunique())
    for t in (5, 10):
        lo, hi = boot_ci(g, lambda x, t=t: 100 * np.mean(np.abs(100 * (x.pred - x.true) / x.true) <= t))
        m[f"TA@{t}_lo"], m[f"TA@{t}_hi"] = lo, hi
    rows.append(m)
res = pd.DataFrame(rows)
cols = ["method", "n_images", "n_counts", "MAPE", "TA@2.5", "TA@5", "TA@5_lo", "TA@5_hi", "TA@10", "TA@10_lo",
        "TA@10_hi", "TA@15", "TAq@5", "img_both@5", "n_img_both@5", "img_both@10", "n_img_both@10",
        "median_signed_%", "under>5%", "over>5%", "key"]
res = res[cols]
res.to_csv(os.path.join(TAB, "tolerance_legacy13.csv"), index=False, float_format="%.1f")
print(res.drop(columns="key").to_string(index=False, float_format=lambda v: f"{v:.1f}"))

# count level: ours vs GPT-6.1-sol P1 (run 0); exact McNemar on discordant counts, image-cluster bootstrap
a = d[d.key == "est:ours"].set_index(["image", "axis"])
b = d[d.key == "vlm:gpt-6.1-sol|P1|r0"].set_index(["image", "axis"])
j = a[["pred", "true"]].join(b[["pred"]], rsuffix="_g").reset_index()
pr = []
for t in (2.5, 5, 10):
    oa = np.abs(j.pred - j.true) / j.true * 100 <= t
    ob = np.abs(j.pred_g - j.true) / j.true * 100 <= t
    n01, n10 = int((~oa & ob).sum()), int((oa & ~ob).sum())
    p = binomtest(n10, n10 + n01, 0.5).pvalue if n10 + n01 else 1.0
    imgs = j.image.unique()
    diffs = []
    for _ in range(B):
        s = rng.choice(imgs, len(imgs), replace=True)
        jj = pd.concat([j[j.image == i] for i in s])
        diffs.append(100 * (np.mean(np.abs(jj.pred - jj.true) / jj.true * 100 <= t)
                            - np.mean(np.abs(jj.pred_g - jj.true) / jj.true * 100 <= t)))
    lo, hi = np.percentile(diffs, [2.5, 97.5])
    pr.append(dict(tau=t, ours=100 * oa.mean(), gpt=100 * ob.mean(), only_ours=n10, only_gpt=n01, mcnemar_p=p,
                   diff_lo=lo, diff_hi=hi))
pr = pd.DataFrame(pr)
pr.to_csv(os.path.join(TAB, "tolerance_paired.csv"), index=False, float_format="%.3f")
print(pr.to_string(index=False))


# image level: both counts within tau; exact McNemar on discordant images
def img_pass(k, t):
    g = d[d.key == k].copy()
    g["ok"] = (abs(g.pred - g.true) / g.true * 100 <= t)
    return g.groupby("image").ok.all()


out = []
for other in ["vlm:gpt-6.1-sol|P1|r0", "vlm:gpt-6.1-sol|P1|r1", "vlm:gpt-6.1-sol|P1|r2", "vlm:gpt-6.1-sol|P3s|r0",
              "est:gabor", "cnn:synth_r18"]:
    for t in (5, 10):
        a_ = img_pass("est:ours", t)
        b_ = img_pass(other, t).reindex(a_.index).fillna(False).astype(bool)
        n10, n01 = int((a_ & ~b_).sum()), int((~a_ & b_).sum())
        p = binomtest(n10, n10 + n01, 0.5).pvalue if n10 + n01 else 1.0
        out.append(dict(other=other, tau=t, ours=int(a_.sum()), other_n=int(b_.sum()), n_img=len(a_),
                        only_ours=n10, only_other=n01, exact_mcnemar_p=round(p, 3)))
io = pd.DataFrame(out)
io.to_csv(os.path.join(TAB, "tolerance_image_paired.csv"), index=False)
print(io.to_string(index=False))

