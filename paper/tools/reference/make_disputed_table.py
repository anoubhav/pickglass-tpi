"""make_disputed_table.py -- supplement Tab. S17: both annotators' counts on every octave-disputed line
(|log2(A2/A1)| > 0.5), with PG-Lattice's and GPT-6.1-sol P1's counts.

Item 2 of the plan for the reference annotator (not in this repository; SHA-256 9ae1d9ca..., see CHECKSUMS.md) asks
for the counts of both annotators on every disputed line; the disputed-line rule is its item 1 of section 2.

    python paper/tools/reference/make_disputed_table.py [--a1 A1.csv] [--a2 A2.csv] [--out DIR]

Output: <out>/supp_disputed_lines.tex (table*, two side-by-side blocks; the caption is the paper's Tab. S17 caption).
"""
import argparse
import os

import numpy as np
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
ap.add_argument("--a1", default=os.path.join(ROOT, "data", "human_counts", "labels_per_scene_A1.csv"),
                help="A1's (non-expert's) per-scene counts: scene_id, h_tpi, v_tpi")
ap.add_argument("--a2", default=os.path.join(ROOT, "data", "human_counts", "labels_per_scene_A2.csv"),
                help="A2's (reference annotator's) per-scene counts: scene_id, h_tpi, v_tpi")
ap.add_argument("--out", default=os.path.join(ROOT, "paper", "tools", "reference", "out"), help="output directory")
args = ap.parse_args()

A = pd.read_csv(args.a1).set_index("scene_id"); B = pd.read_csv(args.a2).set_index("scene_id")
ours = pd.read_csv(os.path.join(ROOT, "methods/predictions_ours_150.csv")).set_index("id")
w = pd.read_csv(os.path.join(ROOT, "vlm/results/rect150_P1_predictions_wide.csv")).set_index("image_id")
g = {"h": pd.to_numeric(w["gpt-6.1-sol__v"], errors="coerce"), "v": pd.to_numeric(w["gpt-6.1-sol__h"], errors="coerce")}
rows = []
for s in A.index:
    for ax in "hv":
        a, b = A.at[s, f"{ax}_tpi"], B.at[s, f"{ax}_tpi"]
        if abs(np.log2(b / a)) > 0.5:
            gg = g[ax].get(s, np.nan)
            rows.append((s, ax, a, b, b / a, ours.at[s, f"{ax}_count"], gg))
fmt = lambda x: "--" if not np.isfinite(x) else f"{x:.0f}"
cells = [f"{s} & ${ax}$ & {fmt(a)} & {fmt(b)} & {r:.2f} & {fmt(o)} & {fmt(gg)}" for s, ax, a, b, r, o, gg in rows]
half = (len(cells) + 1) // 2
L = ["% generated by paper/tools/reference/make_disputed_table.py (plan for the reference annotator, item 2)",
     "\\begin{table*}[t]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
     "\\begin{tabular}{@{}rcrrrrr@{\\hspace{14pt}}rcrrrrr@{}}", "\\toprule",
     "Scene & ax & A1 & A2 & A2/A1 & \\ours & GPT & Scene & ax & A1 & A2 & A2/A1 & \\ours & GPT \\\\", "\\midrule"]
for i in range(half):
    right = cells[i + half] if i + half < len(cells) else "& & & & & &"
    L.append(f"{cells[i]} & {right} \\\\")
L += ["\\bottomrule", "\\end{tabular}",
      f"\\caption{{The {len(rows)} lines ({len({r[0] for r in rows})} scenes) on which the two annotators differ by more than a factor of 1.41 "
      "($|\\log_2(\\mathrm{A2}/\\mathrm{A1})|>0.5$; rule fixed before the reference annotator's counts were opened): both annotators' counts "
      "(threads per window side), their ratio, and \\ours's and GPT-6.1-sol P1's counts. On these lines the reference does "
      "not fix the octave.}", "\\label{tab:supp_disputed}", "\\end{table*}"]
os.makedirs(args.out, exist_ok=True)
open(os.path.join(args.out, "supp_disputed_lines.tex"), "w").write("\n".join(L) + "\n"); print(len(rows), "lines", len({r[0] for r in rows}), "scenes")
