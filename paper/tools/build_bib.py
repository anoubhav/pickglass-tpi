"""Build paper_refs.bib (what main.tex cites) from refs.bib + refs_extra.bib.

refs.bib keeps long `note = {...}` fields that record how each entry was verified.
ieeenat_fullname.bst prints `note`, so those notes would appear in the reference list.
This script copies every entry but drops the `note` field; @misc entries that carry a
URL get an access-date note instead (the fixed `note = {Accessed ...}` string set in main()).

Standard library only:  python3 tools/build_bib.py
Re-run whenever refs.bib or refs_extra.bib changes. Never edit paper_refs.bib by hand.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.dirname(HERE)
SOURCES = ["refs.bib", "refs_extra.bib"]
OUT = "paper_refs.bib"


def split_entries(text):
    """Yield (prefix_text, entry_text) chunks; entry_text starts at '@' and ends at its
    matching closing brace."""
    i, n = 0, len(text)
    while i < n:
        j = text.find("@", i)
        if j < 0:
            return
        k = text.find("{", j)
        if k < 0:
            return
        depth, m = 0, k
        while m < n:
            c = text[m]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    break
            m += 1
        yield text[j:m + 1]
        i = m + 1


def drop_field(entry, field):
    pat = re.compile(r",?\s*\n\s*" + field + r"\s*=\s*\{", re.IGNORECASE)
    while True:
        mt = pat.search(entry)
        if not mt:
            return entry
        start, p, depth = mt.start(), mt.end(), 1
        while depth and p < len(entry):
            if entry[p] == "{":
                depth += 1
            elif entry[p] == "}":
                depth -= 1
            p += 1
        entry = entry[:start] + entry[p:]


def main():
    out, keys = [], []
    header = ("% AUTO-GENERATED by tools/build_bib.py from refs.bib + refs_extra.bib.\n"
              "% Verification notes are stripped so they do not print. Do not edit by hand.\n\n")
    for src in SOURCES:
        text = open(os.path.join(PAPER, src), encoding="utf-8").read()
        for e in split_entries(text):
            head = re.match(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", e)
            if not head:
                continue  # @String/@comment etc.
            typ, key = head.group(1).lower(), head.group(2)
            if typ in ("string", "comment", "preamble"):
                out.append(e)
                continue
            if key in keys:
                sys.exit(f"duplicate key {key} in {src}")
            keys.append(key)
            e = drop_field(e, "note")
            if typ == "misc" and re.search(r"(howpublished|url)\s*=\s*\{\\url", e, re.IGNORECASE):
                e = e.rstrip()[:-1].rstrip().rstrip(",") + ",\n  note = {Accessed Oct.~2026}\n}"
            # arXiv-only @misc entries: ieeenat_fullname.bst ignores eprint, so print the id
            # (affects only @misc entries with an arXiv eprint and no howpublished)
            mt = re.search(r"\beprint\s*=\s*\{([^}]+)\}", e)
            if (typ == "misc" and mt and re.search(r"archivePrefix\s*=\s*\{arXiv\}", e, re.IGNORECASE)
                    and not re.search(r"\bhowpublished\s*=", e, re.IGNORECASE)):
                e = e.rstrip()[:-1].rstrip().rstrip(",") + ",\n  howpublished = {arXiv:" + mt.group(1).strip() + "}\n}"
            out.append(e)
    with open(os.path.join(PAPER, OUT), "w", encoding="utf-8") as f:
        f.write(header + "\n\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(keys)} entries")


if __name__ == "__main__":
    main()
