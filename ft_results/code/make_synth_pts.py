"""Build synth_pts.py = synth.py (v2, verbatim) + the minimal hooks needed for exact point labels.

The Mac generator (cnn/synth.py) is NOT modified.  This script copies it and applies four
exact, asserted string edits, each marked "# [pts]":
  1. render_fabric(..., return_fields=False)   also returns the continuous yarn coordinates U, V
     (warp yarn j has its centre line at U = j + 0.5, weft yarn i at V = i + 0.5)
  2. camera(..., return_geo=False)             also returns the perspective homography and the
     render / sensor sizes
  3. rectify_window(..., expand=None, return_h=False)  optional outward crop expansion (frame border
     visible) and returns the rectifying homography
  4. (appended) pts_tail.py: generate_pts() + dataset writer
None of the edits draws from the generator's RNG, so for the same seed and expand=None the crop
is bit-identical to synth.generate() (checked by test_synth_pts.py).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "synth.py")).read()

EDITS = [
    ("def render_fabric(p: SynthParams, rng, ppi_r: float, side_px: int, x0_in: float):",
     "def render_fabric(p: SynthParams, rng, ppi_r: float, side_px: int, x0_in: float,\n"
     "                  return_fields: bool = False):  # [pts]"),
    ("    return img.astype(np.float32), height.astype(np.float32)\n",
     "    if return_fields:  # [pts] continuous yarn coordinates (render grid)\n"
     "        return img.astype(np.float32), height.astype(np.float32), U, V\n"
     "    return img.astype(np.float32), height.astype(np.float32)\n"),
    ("def camera(p: SynthParams, rng, refl, height, ppi_r, x0_in):",
     "def camera(p: SynthParams, rng, refl, height, ppi_r, x0_in, return_geo=False):  # [pts]"),
    ("    out = cv2.imdecode(enc, cv2.IMREAD_COLOR)\n    return out, win_t\n",
     "    out = cv2.imdecode(enc, cv2.IMREAD_COLOR)\n"
     "    if return_geo:  # [pts] geometry needed to map crop pixels back to the render grid\n"
     "        return out, win_t, dict(Hm=Hm.astype(np.float64), H=int(H), hs=int(hs))\n"
     "    return out, win_t\n"),
    ("def rectify_window(scene, corners, rng, jitter, out_side=None):",
     "def rectify_window(scene, corners, rng, jitter, out_side=None, expand=None, return_h=False):  # [pts]"),
    ("    Hm = cv2.getPerspectiveTransform(noisy.astype(np.float32), dst)\n"
     "    return cv2.warpPerspective(scene, Hm, (side, side), flags=cv2.INTER_AREA,\n"
     "                               borderMode=cv2.BORDER_REFLECT)\n",
     "    Hm = cv2.getPerspectiveTransform(noisy.astype(np.float32), dst)\n"
     "    if expand is not None:  # [pts] widen the crop by (left, top, right, bottom) fractions of the side\n"
     "        l, t, r, b = expand\n"
     "        ext = np.array([[-l * side, -t * side], [(1 + r) * side - 1, -t * side],\n"
     "                        [(1 + r) * side - 1, (1 + b) * side - 1], [-l * side, (1 + b) * side - 1]], np.float64)\n"
     "        src2 = cv2.perspectiveTransform(ext[None], np.linalg.inv(Hm.astype(np.float64)))[0]\n"
     "        Hm = cv2.getPerspectiveTransform(src2.astype(np.float32), dst)\n"
     "    crop = cv2.warpPerspective(scene, Hm, (side, side), flags=cv2.INTER_AREA,\n"
     "                               borderMode=cv2.BORDER_REFLECT)\n"
     "    if return_h:  # [pts]\n"
     "        return crop, Hm.astype(np.float64), side\n"
     "    return crop\n"),
]

for old, new in EDITS:
    assert src.count(old) == 1, ("edit target not unique / missing", old[:80])
    src = src.replace(old, new)

# do not run synth.py's CLI from the patched module
src = src.replace('\nif __name__ == "__main__":\n    main()\n', "\n")
# a comment, not a docstring: synth.py's `from __future__` import must stay first after its docstring
head = ("# synth_pts.py -- GENERATED by make_synth_pts.py from cnn/synth.py (v2); do not edit by hand.\n"
        "# Exact yarn-crossing point labels on top of the unchanged v2 generator (see the [pts] tail).\n")
tail = open(os.path.join(HERE, "pts_tail.py")).read()
open(os.path.join(HERE, "synth_pts.py"), "w").write(head + src + "\n\n" + tail)
print("wrote synth_pts.py")
