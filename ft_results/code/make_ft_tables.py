"""LaTeX snippets for the synthetic-pointing fine-tune (drop-in material; nothing in paper/ is edited).

  tables/legacy13_ft_rows.tex    rows in the format of paper/tables/legacy13_unified_main.tex (Tab. 2)
  tables/ft_supp_table.tex       supplement table: synthetic val + legacy-13, base vs LoRA, every readout
"""
from __future__ import annotations

import json
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
FTR = os.path.dirname(HERE)
T = pd.read_csv(os.path.join(FTR, "tables", "legacy13_ft.csv"))
T = T[T["assign"] == "axis"]
S = pd.read_csv(os.path.join(FTR, "results", "synval_scores.csv"))
M = pd.read_csv(os.path.join(FTR, "results", "synval_point_matching_summary.csv"))
PR = pd.read_csv(os.path.join(FTR, "tables", "legacy13_ft_paired.csv"))
PR = PR[PR["assign"] == "axis"]
sel = json.load(open(os.path.join(FTR, "results", "selection.json")))
prim = sel["primary"]
NAME = {"P1": "P1", "P4": "P4", "P4q": "P4q", "P4s": "P4s", "P4q_sp": "P4q, spacing", "P4s_sp": "P4s, spacing"}
MOD = {"molmo2_4b_base": "Molmo2-4B", "molmo2_4b_synthft": "Molmo2-4B + synth.\\ LoRA"}


def row_main(model, meth, mark=""):
    r = T[T.key == f"ft:{model}|{meth}"]
    if not len(r):
        return None
    r = r.iloc[0]
    return (f"{MOD[model]}, {NAME[meth]}{mark} & {r.MAE:.1f} & {r.MAPE:.1f} [{r.MAPE_lo:.0f}, {r.MAPE_hi:.0f}] & "
            f"{int(r.n_w5)} & {int(r.n_w10)} & GPU \\\\")


lines = ["% Generated by ft_results/code/make_ft_tables.py -- rows for tab:legacy (paper/tables/legacy13_unified_main.tex)",
         f"% primary readout fixed on synthetic validation: {prim}"]
for model, meth, mark in (("molmo2_4b_base", "P4s", ""), ("molmo2_4b_synthft", prim, "$^d$"),
                          ("molmo2_4b_synthft", "P4s", "$^d$")):
    x = row_main(model, meth, mark)
    if x:
        lines.append(x)
lines.append("% footnote: $^d$LoRA-tuned on 12k procedurally rendered crops with exact crossing points; no real "
             "labels; readout chosen on synthetic validation.")
open(os.path.join(FTR, "tables", "legacy13_ft_rows.tex"), "w").write("\n".join(lines) + "\n")

# ---------------------------------------------------------------- supplement table
out = [r"% Generated by ft_results/code/make_ft_tables.py", r"\begin{table}[t]", r"\centering", r"\footnotesize",
       r"\setlength{\tabcolsep}{2pt}", r"\begin{tabular}{@{}llccccc@{}}", r"\toprule",
       r" & & \multicolumn{2}{c}{Synthetic val (100 crops)} & \multicolumn{3}{c}{Legacy-13 (26 counts)} \\",
       r"\cmidrule(lr){3-4}\cmidrule(l){5-7}",
       r"Model & Readout & MAPE [CI] & $\le$10\% & MAPE [CI] & $\le$10\% & $\Delta$ vs base [CI] \\", r"\midrule"]
for model in ("molmo2_4b_base", "molmo2_4b_synthft"):
    for meth in ("P1", "P4", "P4q", "P4s"):
        s = S[(S.model == model) & (S.method == meth)]
        t = T[T.key == f"ft:{model}|{meth}"]
        if not len(s) and not len(t):
            continue
        sc = (f"{s.iloc[0].MAPE:.1f} [{s.iloc[0].MAPE_lo:.0f}, {s.iloc[0].MAPE_hi:.0f}] & {100 * s.iloc[0].w10:.0f}\\%"
              if len(s) else "-- & --")
        lc = (f"{t.iloc[0].MAPE:.1f} [{t.iloc[0].MAPE_lo:.0f}, {t.iloc[0].MAPE_hi:.0f}] & {int(t.iloc[0].n_w10)}"
              if len(t) else "-- & --")
        d = "--"
        if model == "molmo2_4b_synthft":
            lab = (f"FT {prim} vs base 4B {prim}" if meth == prim else f"[secondary] FT {meth} vs base 4B {meth}")
            p = PR[PR.comparison == lab]
            if len(p):
                p = p.iloc[0]
                d = f"{p.dMAPE:+.1f} [{p.dMAPE_lo:+.0f}, {p.dMAPE_hi:+.0f}]".replace("-", "$-$")
        star = "$^\\ast$" if (model == "molmo2_4b_synthft" and meth == prim) else ""
        out.append(f"{MOD[model]} & {NAME[meth]}{star} & {sc} & {lc} & {d} \\\\")
    out.append(r"\midrule")
out[-1] = r"\bottomrule"
pm = M.set_index(["model", "scale"])


def pmf(model, scale, col):
    try:
        return pm.loc[(model, scale), col]
    except KeyError:
        return np.nan


def sp(m):
    t = T[T.key == f"ft:molmo2_4b_synthft|{m}"].iloc[0]
    return f"{t.MAPE:.1f}\\%"


cap = (r"\caption{Molmo2-4B before and after LoRA tuning on synthetic pointing data only. Synthetic val: 100 held-out "
       r"generator crops, error against the exact crossing counts (CI: bootstrap over crops). Legacy-13: unified scorer "
       r"of \cref{tab:legacy}, axis-matched; $\Delta$: paired bootstrap over images, LoRA minus base. P4: points on a "
       r"guide line across the whole inch; P4q: central quarter inch $\times4$; P4s: sum over the four diagonal quarter "
       r"inches. $^\ast$Primary readout, fixed on synthetic validation before legacy scoring. "
       f"Spacing readouts ((points$-1$)/span) give the same picture (LoRA, legacy: P4q {sp('P4q_sp')}, P4s {sp('P4s_sp')}). "
       r"The tuned model's point lists are evenly spaced lattices (gaps vary by at most one coordinate unit in 100\% of "
       r"whole-inch and 90\% of quarter-inch lists; median gap CV 0.000 vs 0.04 / 0.02 for the exact crossings): it reads "
       r"the pitch, and on quarter-inch views partly the phase, but does not trace individual yarns." + "}")
out += [r"\end{tabular}", cap, r"\label{tab:supp_ft}", r"\end{table}"]
open(os.path.join(FTR, "tables", "ft_supp_table.tex"), "w").write("\n".join(out) + "\n")
print("\n".join(lines))
print("\n".join(out))
