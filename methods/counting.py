"""counting.py -- "ours-2026": thread-density and weave estimators for 1-inch pick-glass crops.

All estimators share one interface::

    estimate(crop_bgr, method="ours", **opts) -> {
        "h_count":  float  # vertical yarns crossing a horizontal line, per crop width
                           # (= ends/picks per inch, because the rectified crop is 1 inch)
        "v_count":  float  # horizontal yarns crossing a vertical line, per crop height
        "weave":    str    # plain | twill_2_1 | twill_3_1 | twill_2_2 | satin | other | unknown
        "confidence": float in [0, 1]
        "debug":    dict   # angles, spectral SNR, per-tile votes, capture-quality features ...
    }

Methods (``method=``)
---------------------
"fft"     (a) 2-D power spectrum of the pre-processed crop (Hann window).  The spectrum is
          whitened by its radial median, local maxima are found, and for each yarn family
          (vertical yarns <-> peaks near the u axis, horizontal yarns <-> near the v axis) the
          fundamental is the candidate maximising a 1/k-weighted harmonic sum.  Rationale (see
          ``weave_lattice_note``): for every regular weave (plain, twill, satin) whose float
          lattice is generated by (1, s) and (0, R) in yarn units, the reciprocal lattice
          contains *no* on-axis points except integer multiples of the yarn frequency, so
          weave-repeat sub-harmonics (twill lines, plain-weave checkerboard) are all off-axis
          and the first strong on-axis peak IS the yarn frequency.
"profile" (b) Projection profile.  For each family the image is sheared (x' = x - (y-c)tan a)
          so the yarns become axis-parallel (a found by maximising the band-limited
          periodogram peak of the projection), averaged along the yarn direction, and the
          period of the 1-D profile is found with the YIN cumulative-mean-normalised
          difference function (first dip below threshold -> robust to octave errors),
          with parabolic sub-sample refinement.  Shearing keeps distances along the guide
          line, so count = crop length / period is exactly the guide-line crossing count.
"peaks"   (b') naive direct count: number of maxima of the smoothed profile (what a needle
          count / the 2019 transition count does), period-prior free.
"gabor"   (c) log-Gabor filter bank (36 log-spaced radial frequencies x 3 orientations per
          family) applied in the Fourier domain; local amplitude maps -> per-pixel harmonic-
          weighted best frequency -> amplitude-weighted median over the crop.  Gives a local
          density map (useful for figures and for spotting shadow / glare regions).
"tiles"   (d) local-window voting: the fft estimator on a 3x3 grid of half-size tiles
          (stride 1/4), robust median; the tile agreement is a built-in confidence.
"lattice" (e) MAIN spectral estimator: joint reciprocal-lattice hypothesis search over
          (a, b, weave sub-lattice) -- see est_lattice -- with cluster-centroid refinement.
"fusion3" the v0 fusion: fft accepted when the profile agrees within 6 %, else
          fft+tiles / profile+tiles agreement, else median of three.
"ours"    FINAL: lattice fused with the profile/YIN and fft-tile estimators by the same
          agreement rule (_fuse), weave label from the lattice, confidence = logistic model
          (conf_model.json) on no-reference features (yarn-peak strength g_min, hypothesis
          margin, tile support, estimator agreement, ...), fitted on synthetic data only.

Development log (all choices made on the 300 labelled SYNTHETIC images cnn/data/synth_val via
eval_synth.py / dev_lattice_ablation.py; the 13 hand-counted legacy images were not looked at
until the configuration was frozen; within-10 % rate averaged over both axes):
  v0 fft 0.76 | v0 fusion3 0.79 | glare mask fixed (min-channel + solid-blob rule; v0 'any
  channel >= 245' erased white yarns): fft 0.79, fusion3 0.83 | lattice v1 (order<=3 'finer'
  penalty) 0.74 -> explanations at any order + harmonic-envelope term + strong rigid-rotation
  prior 0.76 -> centroid refinement (w5 0.67 -> 0.72) | score-term ablation: rotation prior
  +6 pts, cross terms +3.5, weave sub-lattice +3.2, finer-unexplained +2.5, envelope +0.5,
  on-axis sub-harmonic penalty -3.3 at weight 1 (kept at 0.25: same w10, lower MAPE) |
  lattice 0.795 -> +fusion 0.843 (fft+fusion 0.830).  Final synthetic: ours 0.853 / 0.830
  (h / v), lattice 0.80 / 0.79, fft 0.78 / 0.79 (optimistic: this is the dev set).

Pre-processing (``preproc=``): "lcn" (default; PCA colour->grey projection that maximises
texture contrast, then local contrast normalisation (I - G_s1*I)/sqrt(G_s2*(.)^2) with
s1 = S/40, s2 = S/16, which removes LED hot spots and shadow gradients), "clahe" (CLAHE then
LCN), "none" (luminance minus its mean).  ``glare=`` "mask" (default: saturated pixels
(max channel >= 245, dilated) are excluded from the normalisation and zeroed afterwards with a
feathered weight), "inpaint" (cv2.inpaint Telea on the grey image), or "off".

All internal processing happens on a square working image of side min(S, ``max_work``)
(INTER_AREA down-sampling, never up-sampling); counts are expressed per crop side and are
therefore resolution independent.
"""
from __future__ import annotations

import math
import time

import cv2
import numpy as np
from scipy import ndimage, signal

R_MIN = 18.0           # lowest thread density searched (threads per crop side)
R_MAX_ABS = 320.0      # highest thread density searched
NYQ_FRAC = 0.42        # never search above 0.42 cycles / working pixel
WEAVES = ("plain", "twill_2_1", "twill_3_1", "twill_2_2", "satin", "other", "unknown")

weave_lattice_note = """Float lattice of a regular weave with repeat R and move number s:
{(i, s*i + R*m)} = span{(1, s), (0, R)} in (end, pick) units.  Reciprocal lattice:
{k : kx + s*ky in Z, R*ky in Z}.  On-axis points (kx, 0) need kx in Z; (0, ky) need s*ky in Z
and R*ky in Z, i.e. ky in Z because gcd(s, R) = 1.  Hence in the yarn-aligned frame only
integer multiples of the yarn frequency lie on the axes; weave sub-harmonics (1/R, -s/R ...)
are off-axis (plain: (1/2, 1/2); 2/1 twill: (1/3, -1/3); 5-end satin s=2: (1/5, 3/5) ...).
Colour patterns (stripes, checks, houndstooth) break this, but their repeats are >= 4 yarns
and mostly below R_MIN."""


# =============================================================================== utilities
def _hann2d(n: int) -> np.ndarray:
    w = np.hanning(n).astype(np.float32)
    return np.outer(w, w)


def _parabolic(ym1, y0, yp1):
    d = ym1 - 2 * y0 + yp1
    if abs(d) < 1e-12:
        return 0.0
    return float(np.clip(0.5 * (ym1 - yp1) / d, -0.5, 0.5))


def _band(n_work: int):
    return R_MIN, float(min(R_MAX_ABS, NYQ_FRAC * n_work))


# ============================================================================ preprocessing
def fast_blur(x: np.ndarray, sigma: float) -> np.ndarray:
    """Gaussian blur; large sigmas are computed on a decimated grid (result is smooth)."""
    if sigma <= 6:
        return cv2.GaussianBlur(x, (0, 0), sigma)
    f = max(1, int(sigma / 3))
    h, w = x.shape[:2]
    small = cv2.resize(x, (max(4, w // f), max(4, h // f)), interpolation=cv2.INTER_AREA)
    small = cv2.GaussianBlur(small, (0, 0), sigma / f)
    return cv2.resize(small, (w, h), interpolation=cv2.INTER_LINEAR)


def glare_mask(bgr: np.ndarray, thr: int = 245, blob_frac: float = 0.85, max_area: float = 0.35) -> np.ndarray:
    """Specular-glare mask: *solid blobs* of saturated pixels, dilated by ~S/250 + 1 px.

    A pixel is saturated if its MIN channel >= thr (specular LED glare is white; a bright
    but coloured yarn is not).  Isolated saturated yarn crowns on white fabric are kept: a
    pixel is glare only if >= blob_frac of a (S/60)-wide box around it is saturated.  If
    the resulting mask exceeds max_area of the crop the whole capture is over-exposed (no
    texture left to protect) and no mask is returned.
    (v0 used "any channel >= 245", which erased bright white yarns -- see dev notes.)
    """
    sat = (bgr.min(axis=2) >= thr).astype(np.float32)
    if not sat.any():
        return np.zeros(bgr.shape[:2], bool)
    k = max(5, int(round(bgr.shape[0] / 60)) | 1)
    dens = cv2.blur(sat, (k, k))
    m = ((dens >= blob_frac) & (sat > 0)).astype(np.uint8)
    if m.any():
        r = int(round(bgr.shape[0] / 250)) + 1 + k // 2
        m = cv2.dilate(m, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * r + 1, 2 * r + 1)))
    if m.mean() > max_area:
        return np.zeros(bgr.shape[:2], bool)
    return m.astype(bool)


def pca_gray(bgr: np.ndarray) -> np.ndarray:
    """Project colour onto the principal axis of the high-passed colour texture.

    Colour fabrics (e.g. blue/white yarn-dyed) often have more yarn contrast in chroma than
    in luminance; the first PCA axis of the high-pass colour vectors captures it.  Sign is
    chosen to correlate positively with luminance; output scaled to the luminance range.
    """
    f = bgr.astype(np.float32)
    s = max(2.0, f.shape[0] / 60)
    hp = f - fast_blur(f, s)
    X = hp.reshape(-1, 3)
    if X.shape[0] > 200000:
        X = X[:: X.shape[0] // 200000 + 1]
    C = np.cov(X.T)
    w, V = np.linalg.eigh(C)
    v = V[:, -1]
    lum = np.array([0.114, 0.587, 0.299])
    if v @ lum < 0:
        v = -v
    g = f @ v.astype(np.float32)
    lumv = f @ lum.astype(np.float32)
    g = (g - g.mean()) / (g.std() + 1e-6) * lumv.std() + lumv.mean()
    return g


def preprocess(crop_bgr: np.ndarray, preproc: str = "lcn", glare: str = "mask",
               max_work: int = 1024, gray: str = "pca"):
    """Return (g, weight, S_work, info): float32 zero-mean texture image at working size.

    weight is a [0, 1] map (0 at glare) already multiplied into g.
    """
    S0 = crop_bgr.shape[0]
    if crop_bgr.shape[0] != crop_bgr.shape[1]:
        S0 = max(crop_bgr.shape[:2])
        crop_bgr = cv2.resize(crop_bgr, (S0, S0), interpolation=cv2.INTER_LINEAR)
    N = int(min(S0, max_work))
    img = crop_bgr if N == S0 else cv2.resize(crop_bgr, (N, N), interpolation=cv2.INTER_AREA)
    info = {"S_native": int(S0), "S_work": N}
    gm_all = glare_mask(img)
    gm = gm_all if glare != "off" else np.zeros(img.shape[:2], bool)
    info["glare_frac"] = float(gm_all.mean())
    info["sat_frac"] = float((img.min(axis=2) >= 245).mean())
    info["dark_frac"] = float((img.max(axis=2) <= 20).mean())
    g = pca_gray(img) if gray == "pca" else cv2.cvtColor(img, cv2.COLOR_BGR2GRAY).astype(np.float32)
    if glare == "inpaint" and gm.any():
        g8 = np.clip(g, 0, 255).astype(np.uint8)
        g = cv2.inpaint(g8, gm.astype(np.uint8), 5, cv2.INPAINT_TELEA).astype(np.float32)
        gm = np.zeros_like(gm)  # nothing left to mask
    valid = (~gm).astype(np.float32)
    if preproc in ("lcn", "clahe"):
        if preproc == "clahe":
            g8 = np.clip(g, 0, 255).astype(np.uint8)
            cl = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
            g = cl.apply(g8).astype(np.float32)
        s1, s2 = N / 40.0, N / 16.0
        den = fast_blur(valid, s1) + 1e-6
        mu = fast_blur(g * valid, s1) / den
        hp = (g - mu) * valid
        var = fast_blur(hp * hp, s2) / (fast_blur(valid, s2) + 1e-6)
        sd = np.sqrt(np.maximum(var, 0))
        eps = 0.15 * float(np.median(sd[valid > 0])) if (valid > 0).any() else 1.0
        out = hp / (sd + eps + 1e-6)
        info["shadow_frac"] = float((mu < 0.45 * np.median(mu)).mean())
        info["contrast_rel"] = float(np.median(sd) / (np.median(mu) + 1e-6))
    elif preproc == "hp":
        mu = fast_blur(g, N / 40.0)
        out = (g - mu) * valid
        out /= out.std() + 1e-6
        info["shadow_frac"] = float((mu < 0.45 * np.median(mu)).mean())
        info["contrast_rel"] = float(out.std())
    else:  # "none"
        out = (g - g[valid > 0].mean()) * valid if (valid > 0).any() else g - g.mean()
        out /= out.std() + 1e-6
        info["shadow_frac"] = float("nan")
        info["contrast_rel"] = float("nan")
    # feathered weight (avoid hard mask edges creating spectral streaks)
    if gm.any():
        w = cv2.GaussianBlur(valid, (0, 0), max(1.0, N / 200.0))
        out = out * w
    else:
        w = np.ones_like(out)
    # simple capture-quality features (no-reference)
    gl = cv2.GaussianBlur(g, (0, 0), 1.0)
    lap = cv2.Laplacian(gl, cv2.CV_32F)
    info["sharpness"] = float(lap.var() / (gl.var() + 1e-6))
    info["px_per_inch"] = float(S0)
    return out.astype(np.float32), w.astype(np.float32), N, info


# ============================================================================== spectrum
class Spectrum:
    """Hann-windowed power spectrum, whitened by its radial median, as z-scores."""

    def __init__(self, g: np.ndarray):
        N = g.shape[0]
        self.N = N
        F = np.fft.fftshift(np.fft.fft2(g * _hann2d(N)))
        P = (F.real ** 2 + F.imag ** 2).astype(np.float64)
        self.logP = np.log(P + 1e-12 * P.max() + 1e-30)
        c = N // 2
        self.c = c
        yy, xx = np.indices((N, N))
        self.U = (xx - c).astype(np.float64)  # cycles per crop, horizontal frequency
        self.V = (yy - c).astype(np.float64)
        r = np.hypot(self.U, self.V)
        # radial median background via a polar resampling (fast; robust to the few peaks)
        nr, nt = c, 360
        pol = cv2.warpPolar(self.logP.astype(np.float32), (nr, nt), (float(c), float(c)), float(c),
                            cv2.INTER_LINEAR | cv2.WARP_POLAR_LINEAR)
        med = np.median(pol, axis=0).astype(np.float64)  # per radius (cols = radius)
        med = ndimage.median_filter(med, size=5, mode="nearest")
        W = self.logP - np.interp(r, np.arange(nr) * (c / nr), med)
        Ws = ndimage.gaussian_filter(W, 0.8)
        lo, hi = _band(N)
        band = (r >= lo) & (r <= hi)
        mad = np.median(np.abs(Ws[band] - np.median(Ws[band]))) * 1.4826 + 1e-9
        self.Z = (Ws - np.median(Ws[band])) / mad  # whitened z-score map
        self.r = r
        self.band = (lo, hi)
        self._zm = {}
        self._z0 = {}

    # ---- fast vectorised lookup: max of Z in a (2k+1)^2 box around (u, v) --------------
    def _maxmap(self, k):
        if k not in self._zm:
            m = cv2.dilate(self.Z.astype(np.float32), np.ones((2 * k + 1, 2 * k + 1), np.uint8),
                           borderType=cv2.BORDER_REPLICATE).astype(np.float64)
            self._zm[k] = m
            lo, hi = self.band
            sel = (self.r >= max(5.0, 0.5 * lo)) & (self.r <= hi)
            self._z0[k] = float(np.median(m[sel])) if sel.any() else 0.0
        return self._zm[k]

    @staticmethod
    def _k_for(r):
        return np.where(r < 60, 1, np.where(r < 120, 2, np.where(r < 200, 3, 4)))

    def lookup(self, U, V):
        """Z max in a small box (half-width 1..4 bins, growing with |f| to absorb yarn-spacing
        jitter) around each (U, V), minus the noise baseline of that box size (median of the
        max-filtered map over the band).  Returns (g, r); g = nan outside the grid."""
        U = np.atleast_1d(np.asarray(U, float))
        V = np.atleast_1d(np.asarray(V, float))
        r = np.hypot(U, V)
        ks = self._k_for(r)
        out = np.full(U.shape, np.nan)
        c = self.c
        for k in np.unique(ks):
            m = self._maxmap(int(k))
            sel = ks == k
            x = np.rint(U[sel] + c).astype(int)
            y = np.rint(V[sel] + c).astype(int)
            ok = (x >= 0) & (x < self.N) & (y >= 0) & (y < self.N)
            vals = np.full(x.shape, np.nan)
            vals[ok] = m[y[ok], x[ok]] - self._z0[int(k)]
            out[sel] = vals
        return out, r

    # value of Z near an arbitrary (u, v) (max in a small disc), and refined peak location
    def zmax_near(self, u, v, rad):
        c = self.c
        x0, y0 = int(round(u + c)), int(round(v + c))
        R = int(math.ceil(rad))
        xa, xb = max(0, x0 - R), min(self.N, x0 + R + 1)
        ya, yb = max(0, y0 - R), min(self.N, y0 + R + 1)
        if xa >= xb or ya >= yb:
            return -np.inf, (u, v)
        sub = self.Z[ya:yb, xa:xb]
        yy, xx = np.mgrid[ya:yb, xa:xb]
        d = np.hypot(xx - (u + c), yy - (v + c)) <= rad + 1e-9
        if not d.any():
            return -np.inf, (u, v)
        sv = np.where(d, sub, -np.inf)
        k = np.unravel_index(np.argmax(sv), sv.shape)
        return float(sv[k]), (float(xx[k] - c), float(yy[k] - c))

    def centroid(self, u, v, rel=0.12, ang=5.0, zthr=2.0):
        """Energy-weighted centroid of the spectral peak CLUSTER around (u, v): bins within
        +-rel of |f| radially and +-ang degrees angularly, weight = (z - zthr)+.  Yarn-spacing
        drift, waviness and residual perspective split a yarn peak into several local maxima;
        the centroid estimates the MEAN density over the crop."""
        rr = math.hypot(u, v)
        if rr < 1:
            return float(u), float(v)
        th = math.atan2(v, u)
        R = int(math.ceil(rr * (1 + rel) * math.sin(math.radians(ang)) + rr * rel + 2))
        c = self.c
        x0, y0 = int(round(u + c)), int(round(v + c))
        xa, xb = max(0, x0 - R), min(self.N, x0 + R + 1)
        ya, yb = max(0, y0 - R), min(self.N, y0 + R + 1)
        Uu, Vv, Zz = self.U[ya:yb, xa:xb], self.V[ya:yb, xa:xb], self.Z[ya:yb, xa:xb]
        r = np.hypot(Uu, Vv)
        dth = np.angle(np.exp(1j * (np.arctan2(Vv, Uu) - th)))
        sel = (np.abs(r / rr - 1) <= rel) & (np.abs(dth) <= math.radians(ang))
        w = np.where(sel, np.clip(Zz - zthr, 0, None), 0.0)
        if w.sum() <= 0:
            return float(u), float(v)
        return float((w * Uu).sum() / w.sum()), float((w * Vv).sum() / w.sum())

    def refine(self, u, v):
        """Sub-bin peak location by separable parabolic fits on log P."""
        c = self.c
        x, y = int(round(u + c)), int(round(v + c))
        if not (1 <= x < self.N - 1 and 1 <= y < self.N - 1):
            return float(u), float(v)
        L = self.logP
        dx = _parabolic(L[y, x - 1], L[y, x], L[y, x + 1])
        dy = _parabolic(L[y - 1, x], L[y, x], L[y + 1, x])
        return float(x + dx - c), float(y + dy - c)

    def peaks(self, zmin=4.0, size=5):
        """Local maxima of Z in the frequency band (u>0 or (u==0 and v>0) half plane)."""
        Z = self.Z
        mx = ndimage.maximum_filter(Z, size=size, mode="nearest")
        lo, hi = self.band
        m = (Z == mx) & (Z >= zmin) & (self.r >= lo) & (self.r <= hi)
        m &= (self.U > 0) | ((self.U == 0) & (self.V > 0))
        ys, xs = np.nonzero(m)
        return [(float(self.U[y, x]), float(self.V[y, x]), float(Z[y, x])) for y, x in zip(ys, xs)]


def _family_candidates(sp: Spectrum, axis: str, max_angle=10.0, zmin=3.5, K=3, rule="maxz"):
    """On-axis spectral peak candidates for one yarn family, with their scores.

    axis 'x': vertical yarns -> reciprocal vector near the +u axis; count = |u|.
    axis 'y': horizontal yarns -> near the +v axis;               count = |v|.
    rule 'maxz'     : score = whitened peak z (the dominant on-axis periodicity is the yarn);
    rule 'harmonic' : score = sum_k max(0, z(k f) - 2) / k  (classic harmonic sum).
    Both are multiplied by a mild tilt penalty 1 - 0.3 (angle / max_angle)^2.
    """
    lo, hi = sp.band
    out = []
    for (u, v, z) in sp.peaks(zmin=zmin):
        if axis == "x":
            ang = math.degrees(math.atan2(v, u))  # u > 0 half plane
        else:
            u, v = (u, v) if v > 0 else (-u, -v)
            ang = math.degrees(math.atan2(u, v))
        if abs(ang) > max_angle:
            continue
        rr = math.hypot(u, v)
        harm = []
        for k in range(1, K + 1):
            if k * rr > hi * 1.02:
                break
            zk, _ = sp.zmax_near(k * u, k * v, max(1.5, 0.025 * k * rr))
            harm.append(float(zk))
        if rule == "harmonic":
            score = sum(max(0.0, h - 2.0) / (k + 1) for k, h in enumerate(harm))
        else:
            score = z
        score *= 1.0 - 0.3 * (ang / max_angle) ** 2
        out.append({"u": u, "v": v, "z": float(z), "angle_deg": float(ang), "score": float(score),
                    "harmonics": harm})
    out.sort(key=lambda d: -d["score"])
    return out


def _finalise(sp, c, axis, cands):
    ur, vr = sp.refine(c["u"], c["v"])
    count = abs(ur) if axis == "x" else abs(vr)
    second = [d["score"] for d in cands if d is not c]
    return {"count": float(count), "vec": (ur, vr), "z": c["z"], "angle_deg": c["angle_deg"],
            "score": c["score"], "margin": float(c["score"] - (max(second) if second else 0.0)),
            "harmonics": c["harmonics"], "n_cands": len(cands),
            "cands": [(round(d["u"], 1), round(d["v"], 1), round(d["z"], 1), round(d["angle_deg"], 1))
                      for d in cands[:6]]}


def est_fft(g: np.ndarray, sp: Spectrum | None = None, rule: str = "maxz", joint: bool = True,
            lam: float = 0.15, **kw):
    """(a) spectral estimator.  joint=True picks the (x, y) candidate pair maximising
    score_x + score_y - lam * |angle_x + angle_y| (a rigid rotation of the fabric tilts the two
    reciprocal vectors by +theta and -theta in our angle conventions)."""
    sp = sp or Spectrum(g)
    cx = _family_candidates(sp, "x", rule=rule, **kw)
    cy = _family_candidates(sp, "y", rule=rule, **kw)
    if joint and cx and cy:
        best = None
        for a in cx[:6]:
            for b in cy[:6]:
                sc = a["score"] + b["score"] - lam * abs(a["angle_deg"] + b["angle_deg"])
                if best is None or sc > best[0]:
                    best = (sc, a, b)
        _, a, b = best
    else:
        a = cx[0] if cx else None
        b = cy[0] if cy else None
    fx = _finalise(sp, a, "x", cx) if a else None
    fy = _finalise(sp, b, "y", cy) if b else None
    return fx, fy, sp


# ===================================================================== lattice (ours, main)
def _twill(R, sgn):
    return [(1 / R, sgn / R), (2 / R, 2 * sgn / R), (1 - 1 / R, -sgn / R)]


# characteristic reciprocal-lattice points (yarn units, up to sign / Z^2) of each weave
WEAVE_PTS = {
    "none": [],
    "plain": [(0.5, 0.5), (0.5, -0.5)],
    "twill3Z": _twill(3, -1), "twill3S": _twill(3, 1),
    "twill4Z": _twill(4, -1), "twill4S": _twill(4, 1),
    "satin5a": [(-0.4, 0.2), (0.2, 0.4)], "satin5b": [(0.4, 0.2), (-0.2, 0.4)],
}
SUB_PTS = [(0.5, 0.0), (0.0, 0.5), (1 / 3, 0.0), (0.0, 1 / 3)]
CORE_PTS = [((1, 0), 1.0), ((0, 1), 1.0), ((1, 1), 0.5), ((1, -1), 0.5), ((2, 0), 0.25), ((0, 2), 0.25)]
CORE_KIND = ["yarn", "yarn", "cross", "cross", "harm", "harm"]
LATTICE_DEFAULTS = dict(max_angle=15.0, zcand=3.0, n_cand=10, zsig=7.0, gcap=15.0, w_weave=1.0,
                        w_sub=0.25, w_fine=1.0, w_env=1.0, lam_rot=1.0, rot_tol=1.0, lam_abs=0.1,
                        fine_thr=1.1, max_order=12.5, n_env=8)


def _reps(W):
    """Coset representatives (mod Z^2) of weave W's sub-lattice, both signs, incl. 0."""
    pts = [(0.0, 0.0)]
    for p in WEAVE_PTS[W]:
        for s in (1, -1):
            q = (s * p[0] % 1.0, s * p[1] % 1.0)
            if all(abs(q[0] - a) > 1e-6 or abs(q[1] - b) > 1e-6 for a, b in pts):
                pts.append(q)
    return np.array(pts)


_REPS = {W: _reps(W) for W in WEAVE_PTS}


def _explain(Cq, Qq, B, W, max_order, tol_px):
    """For peaks with basis coords Cq (n,2) and positions Qq (n,2): explained mask and the
    explaining lattice coordinate (integer + weave coset rep) of each peak."""
    reps = _REPS[W]                                  # (m, 2)
    d = Cq[:, None, :] - reps[None, :, :]            # (n, m, 2)
    k = np.rint(d)
    cstar = k + reps[None]                           # nearest point of each coset
    res = (Cq[:, None, :] - cstar) @ B.T             # residual in spectral bins
    dist = np.hypot(res[..., 0], res[..., 1])
    j = np.argmin(dist, axis=1)
    best = cstar[np.arange(len(Cq)), j]
    dmin = dist[np.arange(len(Cq)), j]
    ok = (dmin <= tol_px) & (np.abs(best).max(axis=1) <= max_order) & (np.abs(best).sum(axis=1) > 0)
    return ok, best


def est_lattice(sp: Spectrum, opts: dict | None = None, keep_hyps: bool = False):
    """Joint reciprocal-lattice hypothesis search (main 'ours' estimator).

    Hypothesis H = (a, b, W): a = reciprocal vector of the vertical yarns (near +u axis),
    b = of the horizontal yarns (near +v axis), W = weave sub-lattice (none, plain, 2/1 or
    3/1-2/2 twill Z/S, 5-end satin).  Score (g = whitened z minus noise baseline, capped):

      S = g(a) + g(b) + .5[g(a+b) + g(a-b)] + .25[g(2a) + g(2b)]          lattice evidence
        + w_weave * mean_{p in W} g(B p)                                   weave sub-lattice
        - w_sub  * sum_{p in {(1/2,0),(0,1/2),(1/3,0),(0,1/3)}} g+(B p)     on-axis sub-harmonics
        - w_fine * sum_{significant peaks q finer than the yarn lattice, unexplained by (H,W)} g+(q)
        - lam_rot * |angle(a) + angle(b)|                                  non-rigid skew

    Rationale.  For any regular weave the only ON-AXIS reciprocal points are integer multiples
    of the yarn frequencies (``weave_lattice_note``), so on-axis 1/2, 1/3 sub-harmonics count
    against a hypothesis (it is probably a harmonic).  Yarns are the finest periodic structure
    of a woven fabric: colour stripes / checks / weave repeats are coarser, so significant
    peaks that are FINER than the hypothesised yarn lattice and not explained by it (or its
    harmonics up to order 3, or its weave sub-lattice) count against it (it is probably a
    colour / weave repeat).  Coarser unexplained peaks are allowed (colour patterns).
    The chosen basis is refined by weighted least squares over all explained peaks.
    """
    o = dict(LATTICE_DEFAULTS)
    o.update(opts or {})
    lo, hi = sp.band
    gcap = o["gcap"]

    def G(pts):
        g, r = sp.lookup(pts[:, 0], pts[:, 1])
        bad = (r > hi) | (r < 5.0) | ~np.isfinite(g)
        return np.where(bad, np.nan, np.clip(g, -3.0, gcap))

    # candidates per family -------------------------------------------------------------
    pk = sp.peaks(zmin=o["zcand"])
    cx, cy = [], []
    for (u, v, z) in pk:
        ax = math.degrees(math.atan2(v, u))
        if abs(ax) <= o["max_angle"]:
            cx.append((u, v, z, ax))
        uu, vv = (u, v) if v > 0 else (-u, -v)
        ay = math.degrees(math.atan2(uu, vv))
        if abs(ay) <= o["max_angle"]:
            cy.append((uu, vv, z, ay))
    cx = sorted(cx, key=lambda t: -t[2])[: o["n_cand"]]
    cy = sorted(cy, key=lambda t: -t[2])[: o["n_cand"]]
    if not cx or not cy:
        return None
    # significant peaks for the 'finer & unexplained' penalty (full band down to 5 cycles)
    Zs = sp.Z
    mx = ndimage.maximum_filter(Zs, size=5, mode="nearest")
    m = (Zs == mx) & (Zs >= o["zsig"]) & (sp.r >= 5.0) & (sp.r <= hi)
    m &= (sp.U > 0) | ((sp.U == 0) & (sp.V > 0))
    ys, xs = np.nonzero(m)
    P = np.stack([sp.U[ys, xs], sp.V[ys, xs]], 1) if len(xs) else np.zeros((0, 2))
    zP = Zs[ys, xs] if len(xs) else np.zeros(0)
    if len(P) > 80:
        o_ = np.argsort(-zP)[:80]
        P, zP = P[o_], zP[o_]
    sp._maxmap(1)
    gP = np.clip(zP - sp._z0[1], 0, gcap)
    rP = np.hypot(P[:, 0], P[:, 1]) if len(P) else np.zeros(0)
    tolP = np.maximum(1.5, 0.03 * rP)

    core_c = np.array([c for c, _ in CORE_PTS], float)
    core_w = np.array([w for _, w in CORE_PTS])
    core_w = core_w * np.array([{"yarn": 1.0, "cross": o.get("w_cross", 1.0), "harm": o.get("w_harm", 1.0)}[k]
                                for k in CORE_KIND])
    sub_c = np.array(SUB_PTS, float)
    nn = np.arange(2, o["n_env"] + 1, dtype=float)
    env_w = np.where(nn <= 3, 0.5, 1.0)
    weaves = list(WEAVE_PTS)
    # one batched list of lattice coordinates per hypothesis: core | sub | env-a | env-b | weave pts
    wpts = [np.array(WEAVE_PTS[W], float).reshape(-1, 2) for W in weaves]
    blocks = [core_c, sub_c, np.stack([nn, 0 * nn], 1), np.stack([0 * nn, nn], 1)] + wpts
    sizes = [len(b) for b in blocks]
    offs = np.cumsum([0] + sizes)
    ALLC = np.concatenate(blocks, 0)
    # coset representatives of all weaves (for the explanation test), with weave membership
    rep_list, rep_w = [], []
    for wi, W in enumerate(weaves):
        for r in _REPS[W]:
            rep_list.append(r)
            rep_w.append(wi)
    REPS = np.array(rep_list)
    REPW = np.array(rep_w)
    member = np.stack([(REPW == wi) | np.all(REPS == 0, axis=1) for wi in range(len(weaves))], 0)  # (nW, nR)
    hyps = []
    for a in cx:
        for b in cy:
            B = np.array([[a[0], b[0]], [a[1], b[1]]], float)
            det = B[0, 0] * B[1, 1] - B[0, 1] * B[1, 0]
            if abs(det) < 1e-6:
                continue
            Binv = np.array([[B[1, 1], -B[0, 1]], [-B[1, 0], B[0, 0]]]) / det
            gall = G(ALLC @ B.T)
            gc = gall[offs[0]:offs[1]]
            s_core = float(np.nansum(core_w * gc))
            s_sub = float(np.nansum(np.clip(gall[offs[1]:offs[2]], 0, None)))
            s_env = 0.0
            for j, g1 in ((2, gc[0]), (3, gc[1])):
                gh = gall[offs[j]:offs[j + 1]]
                s_env += float(np.nansum(env_w * np.clip(gh - (g1 if np.isfinite(g1) else 0.0), 0, None)))
            rot = abs(a[3] + b[3])
            s_rot = o["lam_rot"] * max(0.0, rot - o["rot_tol"]) + o["lam_abs"] * 0.5 * (abs(a[3]) + abs(b[3]))
            if len(P):
                Cq = P @ Binv.T
                fine = np.abs(Cq).max(axis=1) > o["fine_thr"]
                d = Cq[:, None, :] - REPS[None]
                cst = np.rint(d) + REPS[None]                          # (n, nR, 2)
                res = (Cq[:, None, :] - cst) @ B.T
                dist = np.hypot(res[..., 0], res[..., 1])
                good = (dist <= tolP[:, None]) & (np.abs(cst).max(axis=2) <= o["max_order"]) \
                    & (np.abs(cst).sum(axis=2) > 0)                      # (n, nR)
                expl = (good[:, None, :] & member[None]).any(axis=2)   # (n, nW)
                s_fine_W = ((fine[:, None] & ~expl) * gP[:, None]).sum(axis=0)
            else:
                s_fine_W = np.zeros(len(weaves))
            base = s_core - o["w_sub"] * s_sub - o["w_env"] * s_env - s_rot
            for wi, W in enumerate(weaves):
                if sizes[4 + wi]:
                    gw = gall[offs[4 + wi]:offs[5 + wi]]
                    s_w = float(np.nanmean(gw)) if np.isfinite(gw).any() else 0.0
                else:
                    s_w = 0.0
                S = base + o["w_weave"] * s_w - o["w_fine"] * float(s_fine_W[wi])
                hyps.append((S, a, b, W, dict(core=s_core, weave=s_w, sub=s_sub, fine=float(s_fine_W[wi]),
                                              env=s_env, rot=rot, g_a=float(gc[0]), g_b=float(gc[1]))))
    hyps.sort(key=lambda h: -h[0])
    S, a, b, W, parts = hyps[0]
    # ---- refinement: weighted LS fit of the basis to all explained peaks ----------------
    au, av = sp.refine(a[0], a[1])
    bu, bv = sp.refine(b[0], b[1])
    B0 = np.array([[au, bu], [av, bv]])
    B = B0.copy()
    n_fit = 0
    if len(P) >= 3:
        Pr = np.array([sp.refine(u, v) for u, v in P])
        Cq = Pr @ np.linalg.inv(B0).T
        ok, cst = _explain(Cq, Pr, B0, W, o["max_order"], tolP)
        sel = ok & (np.abs(cst).max(axis=1) <= 3.01)
        if sel.sum() >= 3:
            Cs, Qs, ws = cst[sel], Pr[sel], np.minimum(zP[sel], 20.0)
            A = (Cs * ws[:, None]).T @ Cs
            if np.linalg.cond(A) < 1e6:
                Bf = ((Qs * ws[:, None]).T @ Cs) @ np.linalg.inv(A)
                if abs(Bf[0, 0] / B0[0, 0] - 1) < 0.04 and abs(Bf[1, 1] / B0[1, 1] - 1) < 0.04:
                    B, n_fit = Bf, int(sel.sum())
    # cluster-centroid estimate of the yarn frequencies (default output, see Spectrum.centroid)
    acu, acv = sp.centroid(a[0], a[1], rel=o.get("cent_rel", 0.12))
    bcu, bcv = sp.centroid(b[0], b[1], rel=o.get("cent_rel", 0.12))
    Bc = np.array([[acu, bcu], [acv, bcv]])
    refine_mode = o.get("refine", "centroid")
    Bout = {"centroid": Bc, "peak": B0, "lsq": B}[refine_mode]
    # runner-up hypothesis with a materially different count (ambiguity margin)
    alt = None
    for h in hyps[1:]:
        if abs(h[1][0] / a[0] - 1) > 0.08 or abs(h[2][1] / b[1] - 1) > 0.08:
            alt = h
            break
    # best score per weave for this (a, b)
    wscores = {h[3]: round(h[0], 2) for h in hyps if h[1] is a and h[2] is b}
    res = {"h_count": float(abs(Bout[0, 0])), "v_count": float(abs(Bout[1, 1])), "B": Bout.tolist(),
           "B_peak": B0.tolist(), "B_lsq": B.tolist(), "B_centroid": Bc.tolist(), "refine": refine_mode,
           "n_fit": n_fit, "score": float(S), "weave_W": W, "parts": parts,
           "angle_x": float(math.degrees(math.atan2(Bout[1, 0], Bout[0, 0]))),
           "angle_y": float(math.degrees(math.atan2(Bout[0, 1], Bout[1, 1]))),
           "z_a": float(a[2]), "z_b": float(b[2]),
           "margin": float(S - alt[0]) if alt else float(S),
           "alt_counts": (float(abs(alt[1][0])), float(abs(alt[2][1]))) if alt else None,
           "weave_scores": wscores, "n_cx": len(cx), "n_cy": len(cy), "n_sig": int(len(P))}
    if keep_hyps:
        res["hyps"] = [(h[0], h[1][:2], h[2][:2], h[3]) for h in hyps[:30]]
    return res


def lattice_weave_label(sp: Spectrum, lat: dict, thr: float = 2.0) -> str:
    """Weave label from the lattice hypothesis: the selected sub-lattice W, if its mean
    evidence g >= thr, else 'unknown'.  R=4 twills: 2/2 vs 3/1 from the 2nd diagonal
    point (50 % duty suppresses it in 2/2)."""
    if lat is None:
        return "unknown"
    W = lat["weave_W"]
    if W == "none" or lat["parts"]["weave"] < thr:
        return "unknown"
    if W == "plain":
        return "plain"
    if W.startswith("twill3"):
        return "twill_2_1"
    if W.startswith("twill4"):
        B = np.array(lat["B_peak"])
        sgn = -1 if W.endswith("Z") else 1
        g1, _ = sp.lookup(*(B @ np.array([0.25, 0.25 * sgn])))
        g2, _ = sp.lookup(*(B @ np.array([0.5, 0.5 * sgn])))
        return "twill_3_1" if np.nan_to_num(g2[0]) >= 0.5 * np.nan_to_num(g1[0]) else "twill_2_2"
    if W.startswith("satin"):
        return "satin"
    return "other"


def tile_support(g: np.ndarray, B, grid=3, frac=0.5, thr=3.0):
    """Fraction of tiles (grid x grid, size frac*N) in which BOTH yarn peaks predicted by the
    global basis B are present (g >= thr) -- a no-reference 'is the lattice everywhere?' score
    (low under shadow / glare / blur / partial occlusion)."""
    N = g.shape[0]
    t = int(round(frac * N))
    starts = np.linspace(0, N - t, grid).astype(int)
    B = np.asarray(B) * t / N
    hits, gs = [], []
    for y0 in starts:
        for x0 in starts:
            sub = g[y0:y0 + t, x0:x0 + t]
            if np.abs(sub).sum() == 0:
                hits.append(False)
                continue
            sp = Spectrum(sub)
            ga, _ = sp.lookup(B[0, 0], B[1, 0])
            gb, _ = sp.lookup(B[0, 1], B[1, 1])
            v = np.nan_to_num(np.array([ga[0], gb[0]]), nan=-3)
            gs.append(v)
            hits.append(bool((v >= thr).all()))
    return float(np.mean(hits)), (np.array(gs) if gs else np.zeros((0, 2)))


# ============================================================================== weave type
def classify_weave(sp: Spectrum, fx: dict | None, fy: dict | None, zthr=5.0):
    """Rule-based weave classification from the reciprocal lattice in yarn units.

    Basis B = [k_x, k_y] (reciprocal vectors of the two yarn families).  A lattice point c
    (in yarn units) sits at B @ c in the spectrum.  Evidence (whitened z, max in a disc):
      plain : (1/2, 1/2) AND (1/2, -1/2) (same coset; checkerboard of warp/weft floats)
      twill R: (1/R, -1/R)*m (Z) or (1/R, 1/R)*m (S), m = 1..R-1, and the mirror side weak
      satin : (1/R, s/R) with s not in {+-1}, R in {5, 8}
    Returns (label, evidence dict).  If no off-axis structure is significant but both yarn
    families are, the fabric is reported "plain" (plain weave with identical warp/weft
    appearance shows only the yarn peaks); without yarn peaks -> "unknown".
    """
    if fx is None or fy is None:
        return "unknown", {}
    B = np.array([[fx["vec"][0], fy["vec"][0]], [fx["vec"][1], fy["vec"][1]]])
    lo, hi = sp.band

    def z_at(c):
        q = B @ np.asarray(c, dtype=float)
        rr = float(np.hypot(*q))
        if rr < 0.6 * lo or rr > hi:
            return np.nan
        rad = max(1.5, 0.04 * rr)
        return sp.zmax_near(q[0], q[1], rad)[0]

    ev = {}
    ev["plain"] = np.nanmin([z_at((0.5, 0.5)), z_at((0.5, -0.5))])
    tw = {}
    for R in (3, 4):
        for sgn, nm in ((-1, "Z"), (1, "S")):
            zs = [z_at((m / R, sgn * m / R)) for m in range(1, R)]
            tw[(R, nm)] = zs
    # twill evidence: fundamental diagonal point of one handedness vs the other
    best_tw = None
    for R in (3, 4):
        zZ, zS = tw[(R, "Z")][0], tw[(R, "S")][0]
        for z1, z2, nm in ((zZ, zS, "Z"), (zS, zZ, "S")):
            if np.isnan(z1):
                continue
            asym = z1 - (0 if np.isnan(z2) else z2)
            cand = (z1, asym, R, nm)
            if best_tw is None or z1 > best_tw[0]:
                best_tw = cand
    sat = []
    for R, ss in ((5, (2, 3)), (8, (3, 5))):
        for s in ss:
            sat.append(np.nanmax([z_at((1 / R, s / R)), z_at((1 / R, -s / R))]))
    ev["satin"] = float(np.nanmax(sat)) if np.any(np.isfinite(sat)) else np.nan
    ev["twill"] = None if best_tw is None else {"z": best_tw[0], "asym": best_tw[1], "R": best_tw[2],
                                                 "hand": best_tw[3]}
    ev["twill_R3"] = [float(x) for x in tw[(3, "Z")] + tw[(3, "S")]]
    ev["twill_R4"] = [float(x) for x in tw[(4, "Z")] + tw[(4, "S")]]

    yarn_ok = min(fx["z"], fy["z"]) >= zthr
    if best_tw is not None and best_tw[0] >= zthr + 1 and best_tw[1] >= 3.0:
        R = best_tw[2]
        if R == 3:
            return "twill_2_1", ev
        zz = tw[(4, best_tw[3])]
        # 2/2: 50 % duty -> second diagonal harmonic (m=2) suppressed; 3/1: m=2 strong
        if len(zz) >= 2 and not np.isnan(zz[1]) and zz[1] >= 0.8 * zz[0]:
            return "twill_3_1", ev
        return "twill_2_2", ev
    if np.isfinite(ev["satin"]) and ev["satin"] >= zthr + 2 and (np.isnan(ev["plain"]) or ev["satin"] > ev["plain"] + 2):
        return "satin", ev
    if not np.isnan(ev["plain"]) and ev["plain"] >= zthr:
        return "plain", ev
    if yarn_ok:
        return "plain", ev
    return "unknown", ev


# ============================================================================ profile (b)
def _shear(g, w, tan_a, axis):
    """Shear so that yarns of the given family become axis-parallel; returns (img, valid)."""
    N = g.shape[0]
    c = N / 2.0
    if axis == "x":  # vertical yarns: x' = x - (y - c) tan a  -> sample src at x' + (y-c)tan a
        M = np.array([[1.0, tan_a, -c * tan_a], [0.0, 1.0, 0.0]], dtype=np.float32)
    else:  # horizontal yarns: y' = y - (x - c) tan a
        M = np.array([[1.0, 0.0, 0.0], [tan_a, 1.0, -c * tan_a]], dtype=np.float32)
    fl = cv2.INTER_LINEAR | cv2.WARP_INVERSE_MAP
    gi = cv2.warpAffine(g, M, (N, N), flags=fl, borderMode=cv2.BORDER_CONSTANT, borderValue=0)
    wi = cv2.warpAffine(w, M, (N, N), flags=fl, borderMode=cv2.BORDER_CONSTANT, borderValue=0)
    return gi, wi


def _project(g, w, tan_a, axis, rows=None):
    gi, wi = _shear(g, w, tan_a, axis)
    if axis == "x":
        if rows is not None:
            gi, wi = gi[rows[0]:rows[1]], wi[rows[0]:rows[1]]
        num, den = gi.sum(0), wi.sum(0)
    else:
        if rows is not None:
            gi, wi = gi[:, rows[0]:rows[1]], wi[:, rows[0]:rows[1]]
        num, den = gi.sum(1), wi.sum(1)
    p = num / np.maximum(den, 1e-3)
    p[den < 0.2 * den.max()] = 0.0
    return p.astype(np.float64)


def _band_peak_power(p, lo, hi):
    n = len(p)
    q = (p - p.mean()) * np.hanning(n)
    P = np.abs(np.fft.rfft(q)) ** 2
    f = np.arange(len(P))
    m = (f >= lo) & (f <= hi)
    if not m.any():
        return 0.0, 0.0
    k = np.argmax(np.where(m, P, -1))
    return float(P[k] / (np.median(P[m]) + 1e-12)), float(f[k])


def find_angle(g, w, axis, max_angle=12.0):
    """Shear angle (deg) maximising the band-limited periodogram peak of the projection."""
    lo, hi = _band(g.shape[0])
    best = (-1, 0.0)
    for a in np.arange(-max_angle, max_angle + 1e-6, 1.0):
        s, _ = _band_peak_power(_project(g, w, math.tan(math.radians(a)), axis), lo, hi)
        if s > best[0]:
            best = (s, a)
    a0 = best[1]
    for a in np.arange(a0 - 0.9, a0 + 0.91, 0.3):
        s, _ = _band_peak_power(_project(g, w, math.tan(math.radians(a)), axis), lo, hi)
        if s > best[0]:
            best = (s, a)
    return float(best[1]), float(best[0])


def _yin_dprime(p, tau_max):
    p = np.asarray(p, float)
    p = p - ndimage.uniform_filter1d(p, size=max(3, int(2 * tau_max)), mode="reflect")
    n = len(p)
    W = n - tau_max - 1
    d = np.zeros(tau_max + 2)
    for t in range(1, tau_max + 2):
        e = p[:W] - p[t:t + W]
        d[t] = np.dot(e, e)
    cm = np.cumsum(d[1:])
    dn = np.ones_like(d)
    dn[1:] = d[1:] * np.arange(1, len(d)) / np.maximum(cm, 1e-12)
    return dn


def yin_period(profiles, tau_min, tau_max, thr=0.3, rel=0.12):
    """YIN (de Cheveigne & Kawahara 2002) period of one or several 1-D profiles.

    The cumulative-mean-normalised difference d'(tau) is averaged over the given profiles
    (bands of the deskewed image -> robust to yarn bow).  Absolute threshold ``thr`` is
    relaxed adaptively to min(d') + ``rel`` so that low-contrast captures still pick the FIRST
    acceptable dip (shortest period) rather than a multiple of it.  Sub-sample parabolic
    refinement.  Returns (period, d'(period)).
    """
    if isinstance(profiles, np.ndarray) and profiles.ndim == 1:
        profiles = [profiles]
    n = min(len(p) for p in profiles)
    tau_max = int(min(tau_max, n // 2))
    tau_min = max(2, int(math.floor(tau_min)))
    if tau_max <= tau_min + 2:
        return np.nan, np.nan
    dn = np.mean([_yin_dprime(p, tau_max) for p in profiles], axis=0)
    seg = dn[tau_min:tau_max]
    th = max(thr, float(seg.min()) + rel)
    tau = None
    for t in range(tau_min, tau_max):
        if dn[t] < th and dn[t] <= dn[t - 1] and dn[t] <= dn[t + 1]:
            tau = t
            break
    if tau is None:
        tau = tau_min + int(np.argmin(seg))
    tf = tau + _parabolic(dn[tau - 1], dn[tau], dn[tau + 1]) if 1 <= tau < len(dn) - 1 else float(tau)
    return float(tf), float(dn[tau])


def est_profile(g, w, axis, angle_deg=None, yin_thr=0.3, n_bands=4):
    """(b) deskew (shear) + projection along the yarns in n_bands bands + YIN period."""
    N = g.shape[0]
    lo, hi = _band(N)
    if angle_deg is None:
        angle_deg, pk = find_angle(g, w, axis)
    else:
        pk = np.nan
    ta = math.tan(math.radians(angle_deg))
    edges = np.linspace(0, N, n_bands + 1).astype(int)
    profs = [_project(g, w, ta, axis, rows=(a, b)) for a, b in zip(edges[:-1], edges[1:])]
    p = _project(g, w, ta, axis)
    tau, aper = yin_period(profs, N / hi, N / lo, thr=yin_thr)
    count = N / tau if np.isfinite(tau) and tau > 0 else np.nan
    return {"count": float(count), "period_px": tau, "aperiodicity": aper, "angle_deg": angle_deg,
            "peak_snr": pk, "profile": p}


def count_peaks(p, period_hint=None):
    """Direct count of maxima of the smoothed profile (needle-count analogue)."""
    p = np.asarray(p, float)
    if period_hint is None or not np.isfinite(period_hint):
        sm = ndimage.gaussian_filter1d(p, 1.0)
        pk, _ = signal.find_peaks(sm)
    else:
        sm = ndimage.gaussian_filter1d(p, max(0.6, period_hint / 5.0))
        pk, _ = signal.find_peaks(sm, distance=max(1, int(0.6 * period_hint)))
    return int(len(pk)), pk, sm


# ============================================================================== gabor (c)
def est_gabor(g, w, n_freq=36, orients=(-5.0, 0.0, 5.0), sigma_ln=0.13, sigma_deg=4.0,
              max_work=512):
    """Log-Gabor bank; per-pixel harmonic-weighted best frequency; weighted median."""
    N0 = g.shape[0]
    if N0 > max_work:
        g = cv2.resize(g, (max_work, max_work), interpolation=cv2.INTER_AREA)
        w = cv2.resize(w, (max_work, max_work), interpolation=cv2.INTER_AREA)
    N = g.shape[0]
    lo, hi = _band(N)
    freqs = np.geomspace(lo, hi, n_freq)
    step = math.log(freqs[1] / freqs[0])
    G = np.fft.fft2(g)
    fu = np.fft.fftfreq(N) * N
    U, V = np.meshgrid(fu, fu)
    R = np.hypot(U, V) + 1e-9
    TH = np.arctan2(V, U)
    out = {}
    ds = 4  # pooled maps at N/ds
    lnR = np.log(R)
    for axis in ("x", "y"):
        angs = []
        for o in orients:
            th0 = math.radians(o) + (0.0 if axis == "x" else math.pi / 2)
            dth = np.angle(np.exp(1j * (TH - th0)))
            angs.append((np.exp(-dth ** 2 / (2 * math.radians(sigma_deg) ** 2))).astype(np.float32))
        E = np.zeros((n_freq, N // ds, N // ds), np.float32)
        for j, f in enumerate(freqs):
            radial = np.exp(-(lnR - math.log(f)) ** 2 / (2 * sigma_ln ** 2)).astype(np.float32)
            Gr = G * radial
            best = None
            for ang in angs:
                resp = np.abs(np.fft.ifft2(Gr * ang)).astype(np.float32)
                best = resp if best is None else np.maximum(best, resp)
            sm = fast_blur(best, N / 24.0)
            E[j] = cv2.resize(sm, (N // ds, N // ds), interpolation=cv2.INTER_AREA)
        # harmonic-weighted score per pixel: E(f) + E(2f)/2 + E(3f)/3
        H = E.copy()
        for k in (2, 3):
            sh = int(round(math.log(k) / step))
            H[: n_freq - sh] += E[sh:] / k
        jbest = np.argmax(H, axis=0)
        # sub-bin refinement
        jj = np.clip(jbest, 1, n_freq - 2)
        hm = np.take_along_axis(H, (jj - 1)[None], 0)[0]
        h0 = np.take_along_axis(H, jj[None], 0)[0]
        hp = np.take_along_axis(H, (jj + 1)[None], 0)[0]
        den = hm - 2 * h0 + hp
        dj = np.where(np.abs(den) > 1e-9, np.clip(0.5 * (hm - hp) / den, -0.5, 0.5), 0)
        fmap = np.exp(np.log(freqs[0]) + (jj + dj) * step)
        amp = np.take_along_axis(E, jbest[None], 0)[0]
        wt = amp * cv2.resize(w, (N // ds, N // ds), interpolation=cv2.INTER_AREA)
        fv, wv = fmap.ravel(), wt.ravel()
        o = np.argsort(fv)
        cw = np.cumsum(wv[o])
        med = float(fv[o][np.searchsorted(cw, 0.5 * cw[-1])]) if cw[-1] > 0 else np.nan
        agree = float(wv[np.abs(fv / med - 1) < 0.05].sum() / (wv.sum() + 1e-12)) if np.isfinite(med) else 0.0
        out[axis] = {"count": med, "agree": agree, "fmap": fmap.astype(np.float32)}
    return out


# ============================================================================== tiles (d)
def est_tiles(g, grid=3, frac=0.5, **kw):
    """fft estimator on a grid x grid set of tiles of size frac*N; returns per-tile votes."""
    N = g.shape[0]
    t = int(round(frac * N))
    starts = np.linspace(0, N - t, grid).astype(int)
    vx, vy = [], []
    for y0 in starts:
        for x0 in starts:
            sub = g[y0:y0 + t, x0:x0 + t]
            if np.abs(sub).sum() == 0:
                continue
            sp = Spectrum(sub)
            sp.band = (R_MIN * t / N, sp.band[1])  # keep the same physical lower limit
            fx, fy, _ = est_fft(sub, sp=sp, **kw)
            vx.append(np.nan if fx is None else fx["count"] * N / t)
            vy.append(np.nan if fy is None else fy["count"] * N / t)
    vx, vy = np.array(vx), np.array(vy)

    def summ(v):
        v = v[np.isfinite(v)]
        if len(v) == 0:
            return np.nan, 0.0, v
        m = float(np.median(v))
        return m, float(np.mean(np.abs(v / m - 1) < 0.05)), v

    mx, ax, _ = summ(vx)
    my, ay, _ = summ(vy)
    return {"x": {"count": mx, "agree": ax, "votes": vx.tolist()},
            "y": {"count": my, "agree": ay, "votes": vy.tolist()}}


# ============================================================================ main entry
def _rel(a, b):
    if not (np.isfinite(a) and np.isfinite(b)) or b == 0:
        return np.inf
    return abs(a / b - 1)


def _fuse(c_fft, c_prof, c_tile, tol=0.06):
    """ours: accept fft if profile agrees; else majority / median of the three."""
    vals = [v for v in (c_fft, c_prof, c_tile) if np.isfinite(v)]
    if not vals:
        return np.nan, "none"
    if np.isfinite(c_fft) and _rel(c_prof, c_fft) <= tol:
        return float(np.mean([c_fft, c_prof])), "fft+profile"
    if np.isfinite(c_fft) and _rel(c_tile, c_fft) <= tol:
        return float(c_fft), "fft+tiles"
    if np.isfinite(c_prof) and _rel(c_tile, c_prof) <= tol:
        return float(c_prof), "profile+tiles"
    return float(np.median(vals)), "median3"


def _sigmoid(x):
    return 1.0 / (1.0 + math.exp(-x))


CONF_MODEL = None  # filled lazily from conf_model.json (logistic model fitted on synthetic data)


def confidence_from_features(f: dict) -> float:
    """P(both counts within 10 %) from no-reference features.  Uses the logistic model in
    conf_model.json (fitted ONLY on the synthetic dev set by calib_conf.py) when present,
    else a fixed heuristic."""
    global CONF_MODEL
    import json
    import os
    if CONF_MODEL is None:
        p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "conf_model.json")
        CONF_MODEL = json.load(open(p)) if os.path.exists(p) else {}
    if CONF_MODEL:
        x = 0.0 + CONF_MODEL["intercept"]
        for k, (mu, sd, w) in CONF_MODEL["coef"].items():
            v = f.get(k, mu)
            v = mu if v is None or not np.isfinite(v) else v
            x += w * (v - mu) / sd
        return float(_sigmoid(x))
    gmin = f.get("g_min", 0.0)
    ts = f.get("tile_support", 0.5)
    return float(_sigmoid((gmin - 6.0) / 2.5) * (0.4 + 0.6 * ts))


def _cached(cache, key, fn):
    if key not in cache:
        cache[key] = fn()
    return cache[key]


def _estimate_pre(g, w, N, info, method="ours", preproc="lcn", glare="mask", with_weave=True,
                  keep_arrays=False, lattice_opts=None, cache=None):
    """Estimator core on a pre-processed working image; ``cache`` shares the spectrum, lattice,
    fft, profile and tile results between estimators run on the same image."""
    t0 = time.time()
    cache = {} if cache is None else cache
    dbg = {"method": method, "preproc": preproc, "glare": glare, **info}
    hx = vy = np.nan
    weave, conf = "unknown", 0.0
    sp = _cached(cache, "sp", lambda: Spectrum(g))
    fx = fy = None

    if method in ("lattice", "ours"):
        lkey = "lat" if not lattice_opts else ("lat", tuple(sorted(lattice_opts.items())))
        lat = _cached(cache, lkey, lambda: est_lattice(sp, lattice_opts))
        dbg["lattice"] = None if lat is None else {k: v for k, v in lat.items() if k != "hyps"}
        if lat is None and method == "ours":
            # no near-axis yarn candidate in one family (e.g. knits, extreme blur): fall back to
            # the agreement of the two other estimators, flagged with ~zero confidence
            px, py = _cached(cache, "prof", lambda: (est_profile(g, w, "x"), est_profile(g, w, "y")))
            tl = _cached(cache, "tiles", lambda: est_tiles(g))
            hx, sx = _fuse(np.nan, px["count"], tl["x"]["count"])
            vy, sy = _fuse(np.nan, py["count"], tl["y"]["count"])
            dbg["fusion"] = ("nolattice:" + sx, "nolattice:" + sy)
            dbg["components"] = {"lattice": (np.nan, np.nan), "profile": (px["count"], py["count"]),
                                 "tiles": (tl["x"]["count"], tl["y"]["count"])}
            dbg["conf_features"] = {"g_min": 0.0, "tile_support": 0.0, "agree_prof": 0.0}
            conf = 0.01
        if lat is not None:
            hx, vy = lat["h_count"], lat["v_count"]
            weave = lattice_weave_label(sp, lat)
            feats = {"g_min": min(lat["parts"]["g_a"], lat["parts"]["g_b"]), "margin": lat["margin"],
                     "weave_g": lat["parts"]["weave"], "fine": lat["parts"]["fine"],
                     "sharpness": info["sharpness"], "glare_frac": info["glare_frac"]}
            if method == "ours":
                # fusion with two independent estimators (agreement rule of _fuse, chosen on the
                # synthetic dev set): deskewed-profile YIN and fft tile votes
                ts, tg = _cached(cache, ("tsup", lkey), lambda: tile_support(g, lat["B"]))
                px, py = _cached(cache, "prof", lambda: (est_profile(g, w, "x"), est_profile(g, w, "y")))
                tl = _cached(cache, "tiles", lambda: est_tiles(g))
                hx, sx = _fuse(lat["h_count"], px["count"], tl["x"]["count"])
                vy, sy = _fuse(lat["v_count"], py["count"], tl["y"]["count"])
                dbg["fusion"] = (sx, sy)
                dbg["components"] = {"lattice": (lat["h_count"], lat["v_count"]),
                                     "profile": (px["count"], py["count"]),
                                     "tiles": (tl["x"]["count"], tl["y"]["count"])}
                feats["tile_support"] = ts
                feats["agree_prof"] = float(np.mean([_rel(px["count"], lat["h_count"]) <= 0.06,
                                                     _rel(py["count"], lat["v_count"]) <= 0.06]))
                feats["agree_tiles"] = float(min(tl["x"]["agree"], tl["y"]["agree"]))
                feats["fused_lattice"] = float(np.mean([sx in ("fft+profile", "fft+tiles"),
                                                        sy in ("fft+profile", "fft+tiles")]))
                dbg["tile_g"] = tg.tolist()
            dbg["conf_features"] = feats
            conf = confidence_from_features(feats)
        if keep_arrays:
            dbg["spectrum"], dbg["g"], dbg["w"] = sp, g, w
        dbg["runtime_s"] = time.time() - t0
        dbg["N_work"] = N
        return {"h_count": float(hx), "v_count": float(vy), "weave": weave, "confidence": float(conf),
                "debug": dbg}

    need_fft = method in ("fft", "fft_harm", "fusion3") or with_weave
    if need_fft:
        rule = "harmonic" if method == "fft_harm" else "maxz"
        fx, fy, _ = _cached(cache, ("fft", rule), lambda: est_fft(g, sp=sp, rule=rule))
        dbg["fft_x"] = None if fx is None else {k: v for k, v in fx.items()}
        dbg["fft_y"] = None if fy is None else {k: v for k, v in fy.items()}
    c_fft = (fx["count"] if fx else np.nan, fy["count"] if fy else np.nan)
    prof = lambda: (est_profile(g, w, "x"), est_profile(g, w, "y"))  # noqa: E731

    if method in ("fft", "fft_harm"):
        hx, vy = c_fft
        zs = [f["z"] for f in (fx, fy) if f]
        conf = _sigmoid((min(zs) - 8.0) / 3.0) if len(zs) == 2 else 0.0
    elif method in ("profile", "peaks"):
        px, py = _cached(cache, "prof", prof)
        dbg["profile_x"] = {k: v for k, v in px.items() if k != "profile"}
        dbg["profile_y"] = {k: v for k, v in py.items() if k != "profile"}
        if method == "profile":
            hx, vy = px["count"], py["count"]
        else:
            hx = float(count_peaks(px["profile"])[0])
            vy = float(count_peaks(py["profile"])[0])
        conf = float(np.clip(1 - max(px["aperiodicity"], py["aperiodicity"]), 0, 1))
        if keep_arrays:
            dbg["profile_x"]["profile"], dbg["profile_y"]["profile"] = px["profile"], py["profile"]
    elif method == "gabor":
        gb = _cached(cache, "gabor", lambda: est_gabor(g, w))
        hx, vy = gb["x"]["count"], gb["y"]["count"]
        conf = float(min(gb["x"]["agree"], gb["y"]["agree"]))
        dbg["gabor_agree"] = (gb["x"]["agree"], gb["y"]["agree"])
        if keep_arrays:
            dbg["gabor_fmap"] = (gb["x"]["fmap"], gb["y"]["fmap"])
    elif method == "tiles":
        tl = _cached(cache, "tiles", lambda: est_tiles(g))
        hx, vy = tl["x"]["count"], tl["y"]["count"]
        conf = float(min(tl["x"]["agree"], tl["y"]["agree"]))
        dbg["tiles"] = tl
    elif method == "fusion3":
        px, py = _cached(cache, "prof", prof)
        tl = _cached(cache, "tiles", lambda: est_tiles(g))
        dbg["profile_x"] = {k: v for k, v in px.items() if k != "profile"}
        dbg["profile_y"] = {k: v for k, v in py.items() if k != "profile"}
        dbg["tiles"] = tl
        hx, sx = _fuse(c_fft[0], px["count"], tl["x"]["count"])
        vy, sy = _fuse(c_fft[1], py["count"], tl["y"]["count"])
        dbg["fusion"] = (sx, sy)
        zmin = min([f["z"] for f in (fx, fy) if f] or [0.0])
        agree_est = float(np.mean([_rel(px["count"], c_fft[0]) <= 0.06, _rel(py["count"], c_fft[1]) <= 0.06]))
        agree_tile = float(min(tl["x"]["agree"], tl["y"]["agree"]))
        conf = float(_sigmoid((zmin - 8.0) / 3.0) * (0.4 + 0.6 * agree_tile) * (0.5 + 0.5 * agree_est))
        dbg["conf_parts"] = {"zmin": zmin, "agree_tile": agree_tile, "agree_est": agree_est}
    else:
        raise ValueError(method)

    if with_weave and fx is not None:
        weave, wev = classify_weave(sp, fx, fy)
        dbg["weave_evidence"] = wev
    if keep_arrays:
        dbg["spectrum"], dbg["g"], dbg["w"] = sp, g, w
    dbg["runtime_s"] = time.time() - t0
    dbg["N_work"] = N
    return {"h_count": float(hx) if hx is not None else np.nan,
            "v_count": float(vy) if vy is not None else np.nan,
            "weave": weave, "confidence": float(conf), "debug": dbg}


def estimate(crop_bgr: np.ndarray, method: str = "ours", preproc: str = "lcn", glare: str = "mask",
             max_work: int = 1024, with_weave: bool = True, keep_arrays: bool = False,
             lattice_opts: dict | None = None):
    """Unified interface; see module docstring."""
    t0 = time.time()
    g, w, N, info = preprocess(crop_bgr, preproc=preproc, glare=glare, max_work=max_work)
    out = _estimate_pre(g, w, N, info, method, preproc, glare, with_weave, keep_arrays, lattice_opts)
    out["debug"]["runtime_s"] = time.time() - t0
    return out


def estimate_many(crop_bgr: np.ndarray, methods, preproc: str = "lcn", glare: str = "mask",
                  max_work: int = 1024, lattice_opts: dict | None = None):
    """{method: result} for several estimators sharing one pre-processing / spectrum pass.
    Weave is reported by the lattice-based estimators only (classify_weave is skipped)."""
    t0 = time.time()
    g, w, N, info = preprocess(crop_bgr, preproc=preproc, glare=glare, max_work=max_work)
    t_pre = time.time() - t0
    cache = {}
    out = {}
    for m in methods:
        t1 = time.time()
        out[m] = _estimate_pre(g, w, N, info, m, preproc, glare, with_weave=False, lattice_opts=lattice_opts,
                               cache=cache)
        out[m]["debug"]["runtime_s"] = time.time() - t1 + t_pre
    return out


# ====================================================================== guide-line dots
def guide_positions(crop_bgr: np.ndarray, h_count: float, v_count: float, angle_x=0.0, angle_y=0.0,
                    preproc="lcn", glare="mask", max_work=1024, band_frac=0.12):
    """Yarn crossing positions on the centre guide lines, in NATIVE rectified-crop pixels.

    h_positions: x where vertical yarns cross y = S/2; v_positions: y where horizontal yarns
    cross x = S/2.  A phase-locked comb at the estimated period is fitted to a deskewed band
    (+-band_frac*S) around the guide line, then each tooth is snapped to the nearest local
    maximum within +-0.3 period (yarn centres are the bright ridges after PCA-grey, whose sign
    is chosen to correlate with luminance).
    """
    g, w, N, info = preprocess(crop_bgr, preproc=preproc, glare=glare, max_work=max_work)
    S0 = info["S_native"]
    Hn, Wn = crop_bgr.shape[:2]  # non-square crops are analysed as an S0 x S0 resize
    scales = {"x": Wn / N, "y": Hn / N}
    out = {}
    for axis, cnt, ang in (("x", h_count, angle_x), ("y", v_count, angle_y)):
        if not (np.isfinite(cnt) and cnt > 0):
            out[axis] = []
            continue
        T = N / cnt
        b = int(round(band_frac * N))
        c = N // 2
        p = _project(g, w, math.tan(math.radians(ang or 0.0)), axis, rows=(c - b, c + b))
        sm = ndimage.gaussian_filter1d(p, max(0.6, T / 6))
        n = np.arange(N)
        # phase of the fundamental
        z = np.sum(sm * np.exp(-2j * np.pi * n / T))
        phi = np.angle(z)  # maxima at n = T*(phi/2pi + k)  ->  cos(2pi n/T - phi) = 1
        x0 = (phi / (2 * np.pi)) * T
        k0 = int(np.floor((0 - x0) / T))
        teeth = x0 + T * np.arange(k0, k0 + int(cnt) + 4)
        teeth = teeth[(teeth >= 0) & (teeth < N)]
        pos = []
        for tpos in teeth:
            a, bb = int(max(0, math.floor(tpos - 0.3 * T))), int(min(N - 1, math.ceil(tpos + 0.3 * T)))
            seg = sm[a:bb + 1]
            if len(seg) >= 3:
                k = int(np.argmax(seg))
                if 0 < k < len(seg) - 1:
                    xk = a + k + _parabolic(seg[k - 1], seg[k], seg[k + 1])
                else:
                    xk = tpos
            else:
                xk = tpos
            pos.append(xk)
        pos = np.array(sorted(pos))
        # sheared coordinates == native coordinates on the centre line (shear about centre)
        sc = scales[axis]
        lim = Wn if axis == "x" else Hn
        out[axis] = [int(round(v * sc)) for v in pos if 0 <= v * sc < lim]
    return {"rect_size": [int(Wn), int(Hn)], "h_line_y": int(Hn // 2), "h_positions": out["x"],
            "v_line_x": int(Wn // 2), "v_positions": out["y"]}
